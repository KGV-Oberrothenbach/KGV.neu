-- AP-04.4 follow-up: a signed replacement contract may only apply the exact
-- change snapshot that was frozen before its Prepared signature started.
-- Session GUCs are deliberately not used as authorization evidence.
create extension if not exists pgcrypto;

create table public.pacht_vertragsaenderung (
  id bigint generated by default as identity primary key,
  pachtverhaeltnis_id bigint not null references public.pachtverhaeltnis(id) on delete restrict,
  vorgaenger_fassung_id bigint not null references public.pachtvertragsfassung(id) on delete restrict,
  kommunikationsvorgang_id bigint not null unique references public.kommunikationsvorgang(id) on delete restrict,
  pachtvertragsfassung_id bigint unique references public.pachtvertragsfassung(id) on delete restrict,
  aenderungsstand jsonb not null,
  aenderungs_hash text not null,
  begruendung text not null,
  erstellt_von uuid not null references auth.users(id) on delete restrict,
  erstellt_am timestamptz not null default now(),
  signiert_am timestamptz,
  angewendet_am timestamptz,
  angewendet_von uuid references auth.users(id) on delete restrict,
  constraint pacht_vertragsaenderung_stand_chk check (
    jsonb_typeof(aenderungsstand) = 'object'
    and aenderungsstand ?& array['flaeche_qm','hat_strom','hat_wasser']
    and jsonb_typeof(aenderungsstand->'flaeche_qm') = 'number'
    and jsonb_typeof(aenderungsstand->'hat_strom') = 'boolean'
    and jsonb_typeof(aenderungsstand->'hat_wasser') = 'boolean'
  ),
  constraint pacht_vertragsaenderung_hash_chk check (aenderungs_hash ~ '^[0-9a-f]{64}$')
);
alter table public.pacht_vertragsaenderung enable row level security;
revoke all on public.pacht_vertragsaenderung from public, anon, authenticated;

-- This private table is the only short-lived execution proof accepted by the
-- parcel trigger.  Unlike a custom setting it cannot be forged by a caller.
create table public.p11_pacht_aenderung_ausfuehrung (
  pacht_vertragsaenderung_id bigint primary key references public.pacht_vertragsaenderung(id) on delete restrict,
  txid bigint not null,
  erstellt_am timestamptz not null default now()
);
revoke all on public.p11_pacht_aenderung_ausfuehrung from public, anon, authenticated;

create or replace function public.bereite_signierte_parzellen_vertragsaenderung_vor(
  p_vorgaenger_fassung_id bigint,
  p_flaeche_qm numeric,
  p_hat_strom boolean,
  p_hat_wasser boolean,
  p_begruendung text
) returns table(pacht_vertragsaenderung_id bigint, kommunikationsvorgang_id bigint)
language plpgsql security definer set search_path=public,pg_temp as $$
declare
  v_reason text := nullif(btrim(p_begruendung),'');
  v_relation bigint;
  v_change bigint;
  v_process bigint;
  v_snapshot jsonb;
  v_hash text;
begin
  if auth.uid() is null or not public.has_effective_permission(524288) then
    raise exception 'Keine Berechtigung für Vertragsänderungen.' using errcode='42501';
  end if;
  if v_reason is null or p_flaeche_qm is null or p_flaeche_qm < 0
     or p_hat_strom is null or p_hat_wasser is null then
    raise exception 'Vollständiger Änderungsstand und Begründung erforderlich.' using errcode='22023';
  end if;
  select f.pachtverhaeltnis_id into v_relation
  from public.pachtvertragsfassung f join public.pachtverhaeltnis p on p.id=f.pachtverhaeltnis_id
  where f.id=p_vorgaenger_fassung_id and p.beendet_am is null
    and f.nicht_mehr_massgeblich_am is null
    and not exists (select 1 from public.pachtvertragsfassung n where n.vorgaenger_fassung_id=f.id)
  for update;
  if not found then raise exception 'Die maßgebliche laufende Vertragsfassung fehlt.' using errcode='23514'; end if;

  -- Re-use the productive replacement-contract path. It creates the frozen
  -- Prepared revision, mandatory signature positions and the final version.
  select kommunikationsvorgang_id into v_process
  from public.prepare_pachtvertrag_ersatz(p_vorgaenger_fassung_id, auth.uid());
  if exists (select 1 from public.pacht_vertragsaenderung where kommunikationsvorgang_id=v_process) then
    select id into v_change from public.pacht_vertragsaenderung where kommunikationsvorgang_id=v_process;
    return query select v_change, v_process;
    return;
  end if;
  v_snapshot := jsonb_build_object('flaeche_qm',p_flaeche_qm,'hat_strom',p_hat_strom,'hat_wasser',p_hat_wasser);
  v_hash := encode(digest(convert_to(v_snapshot::text,'utf8'),'sha256'),'hex');
  insert into public.pacht_vertragsaenderung(
    pachtverhaeltnis_id,vorgaenger_fassung_id,kommunikationsvorgang_id,aenderungsstand,aenderungs_hash,begruendung,erstellt_von
  ) values (v_relation,p_vorgaenger_fassung_id,v_process,v_snapshot,v_hash,v_reason,auth.uid()) returning id into v_change;
  -- The normal workflow freezes entwurf_daten when signing starts. Storing the
  -- ID and digest there binds its signed revision to this exact server record.
  update public.kommunikationsvorgang
  set entwurf_daten=jsonb_set(jsonb_set(entwurf_daten,'{draft,p11_contract_change_id}',to_jsonb(v_change),true),'{draft,p11_contract_change_hash}',to_jsonb(v_hash),true)
  where id=v_process and status='vorbereitet' and signatur_gestartet_am is null;
  if not found then raise exception 'Der Änderungsentwurf konnte nicht eingefroren werden.' using errcode='40001'; end if;
  return query select v_change,v_process;
end $$;
revoke all on function public.bereite_signierte_parzellen_vertragsaenderung_vor(bigint,numeric,boolean,boolean,text) from public,anon;
grant execute on function public.bereite_signierte_parzellen_vertragsaenderung_vor(bigint,numeric,boolean,boolean,text) to authenticated;

create or replace function public.bind_pacht_vertragsaenderung_an_fassung()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare v_change public.pacht_vertragsaenderung%rowtype; v_process public.kommunikationsvorgang%rowtype;
begin
  select c.*, k.* into v_change, v_process
  from public.pacht_vertragsaenderung c join public.kommunikationsvorgang k on k.id=c.kommunikationsvorgang_id
  join public.dokument d on d.source_kommunikationsvorgang_id=k.id
  where d.id=new.dokument_id for update of c,k;
  if not found then return new; end if;
  if new.pachtverhaeltnis_id is distinct from v_change.pachtverhaeltnis_id
     or new.vorgaenger_fassung_id is distinct from v_change.vorgaenger_fassung_id
     or v_process.entwurf_daten #>> '{draft,p11_contract_change_id}' is distinct from v_change.id::text
     or v_process.entwurf_daten #>> '{draft,p11_contract_change_hash}' is distinct from v_change.aenderungs_hash
     or v_process.signatur_revision is null
     or exists (select 1 from public.prepared_contract_signatur s where s.kommunikationsvorgang_id=v_process.id and s.signatur_revision=v_process.signatur_revision and s.pflicht and s.status<>'unterschrieben') then
    raise exception 'Die Vertragsfassung autorisiert keinen vollständigen eingefrorenen Änderungsstand.' using errcode='23514';
  end if;
  update public.pacht_vertragsaenderung set pachtvertragsfassung_id=new.id, signiert_am=now() where id=v_change.id;
  return new;
end $$;
drop trigger if exists trg_bind_pacht_vertragsaenderung_an_fassung on public.pachtvertragsfassung;
create trigger trg_bind_pacht_vertragsaenderung_an_fassung after insert on public.pachtvertragsfassung
for each row execute function public.bind_pacht_vertragsaenderung_an_fassung();

create or replace function public.guard_pacht_parzellenmerkmale()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if (old.flaeche_qm is distinct from new.flaeche_qm or old.hat_strom is distinct from new.hat_strom or old.hat_wasser is distinct from new.hat_wasser)
    and exists(select 1 from public.pachtverhaeltnis p where p.parzelle_id=old.id and p.beendet_am is null)
    and not exists (
      select 1 from public.p11_pacht_aenderung_ausfuehrung e join public.pacht_vertragsaenderung c on c.id=e.pacht_vertragsaenderung_id
      where e.txid=txid_current() and c.pachtverhaeltnis_id in (select id from public.pachtverhaeltnis where parzelle_id=old.id and beendet_am is null)
        and c.angewendet_am is null
        and jsonb_build_object('flaeche_qm',new.flaeche_qm,'hat_strom',new.hat_strom,'hat_wasser',new.hat_wasser)=c.aenderungsstand
    ) then
   raise exception 'Fläche und Anschlüsse einer laufend verpachteten Parzelle erfordern eine vollständig abgeschlossene Vertragsänderung.' using errcode='42501';
 end if;
 return new;
end $$;

create or replace function public.wende_signierte_parzellen_vertragsaenderung_an(p_pacht_vertragsaenderung_id bigint)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare v_change public.pacht_vertragsaenderung%rowtype; v_old jsonb; v_user uuid:=auth.uid();
begin
 if v_user is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für Vertragsänderungen.' using errcode='42501'; end if;
 select * into v_change from public.pacht_vertragsaenderung where id=p_pacht_vertragsaenderung_id for update;
 if not found then raise exception 'Unbekannte Vertragsänderung.' using errcode='P0002'; end if;
 if v_change.angewendet_am is not null then return true; end if;
 if v_change.pachtvertragsfassung_id is null or v_change.signiert_am is null
    or not exists (select 1 from public.pachtverhaeltnis p where p.id=v_change.pachtverhaeltnis_id and p.beendet_am is null) then
   raise exception 'Vollständig unterschriebene Vertragsänderung fehlt.' using errcode='23514'; end if;
 select jsonb_build_object('flaeche_qm',flaeche_qm,'hat_strom',hat_strom,'hat_wasser',hat_wasser) into v_old
 from public.parzelle pa join public.pachtverhaeltnis p on p.parzelle_id=pa.id where p.id=v_change.pachtverhaeltnis_id for update;
 insert into public.p11_pacht_aenderung_ausfuehrung(pacht_vertragsaenderung_id,txid) values(v_change.id,txid_current());
 update public.parzelle set flaeche_qm=(v_change.aenderungsstand->>'flaeche_qm')::numeric,hat_strom=(v_change.aenderungsstand->>'hat_strom')::boolean,hat_wasser=(v_change.aenderungsstand->>'hat_wasser')::boolean
 where id=(select parzelle_id from public.pachtverhaeltnis where id=v_change.pachtverhaeltnis_id);
 insert into public.pacht_daten_audit(pachtverhaeltnis_id,parzelle_id,pachtvertragsfassung_id,art,vorher,nachher,begruendung,akteur_user_id)
 select p.id,p.parzelle_id,v_change.pachtvertragsfassung_id,'vertragsaenderung',v_old,v_change.aenderungsstand,v_change.begruendung,v_user from public.pachtverhaeltnis p where p.id=v_change.pachtverhaeltnis_id;
 update public.pacht_vertragsaenderung set angewendet_am=now(),angewendet_von=v_user where id=v_change.id;
 delete from public.p11_pacht_aenderung_ausfuehrung where pacht_vertragsaenderung_id=v_change.id;
 return true;
end $$;
revoke all on function public.wende_signierte_parzellen_vertragsaenderung_an(bigint,numeric,boolean,boolean,text) from public,anon,authenticated;
revoke all on function public.wende_signierte_parzellen_vertragsaenderung_an(bigint) from public,anon;
grant execute on function public.wende_signierte_parzellen_vertragsaenderung_an(bigint) to authenticated;

create table public.pacht_historische_berichtigung (
 id bigint generated by default as identity primary key,
 objektart text not null check (objektart in ('pachtverhaeltnis','pachtverhaeltnis_beteiligung','parzellen_belegung','pachtvertragsfassung')),
 original_id bigint not null, vorher jsonb not null, berichtigter_stand jsonb not null,
 begruendung text not null, akteur_user_id uuid not null references auth.users(id) on delete restrict,
 erfasst_am timestamptz not null default now(), unique(objektart,original_id,berichtigter_stand)
);
alter table public.pacht_historische_berichtigung enable row level security;
revoke all on public.pacht_historische_berichtigung from public,anon,authenticated;
create or replace function public.erfasse_historische_pachtberichtigung(p_objektart text,p_original_id bigint,p_berichtigter_stand jsonb,p_begruendung text)
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare v_before jsonb; v_id bigint; v_user uuid:=auth.uid();
begin
 if v_user is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für historische Korrekturen.' using errcode='42501'; end if;
 if nullif(btrim(p_begruendung),'') is null or p_berichtigter_stand is null then raise exception 'Berichtigter Stand und Begründung erforderlich.' using errcode='22023'; end if;
 if p_objektart='pachtverhaeltnis' then select to_jsonb(x) into v_before from public.pachtverhaeltnis x where id=p_original_id and beendet_am is not null;
 elsif p_objektart='pachtverhaeltnis_beteiligung' then select to_jsonb(x) into v_before from public.pachtverhaeltnis_beteiligung x where id=p_original_id and gueltig_bis is not null;
 elsif p_objektart='parzellen_belegung' then select to_jsonb(x) into v_before from public.parzellen_belegung x where id=p_original_id and bis_datum is not null;
 elsif p_objektart='pachtvertragsfassung' then select to_jsonb(x) into v_before from public.pachtvertragsfassung x where id=p_original_id;
 else raise exception 'Unbekannte historische Objektart.' using errcode='22023'; end if;
 if v_before is null then raise exception 'Kein abgeschlossener Originaldatensatz für die Berichtigung.' using errcode='23514'; end if;
 insert into public.pacht_historische_berichtigung(objektart,original_id,vorher,berichtigter_stand,begruendung,akteur_user_id)
 values(p_objektart,p_original_id,v_before,p_berichtigter_stand,btrim(p_begruendung),v_user) returning id into v_id;
 return v_id;
end $$;
revoke all on function public.erfasse_historische_pachtberichtigung(text,bigint,jsonb,text) from public,anon;
grant execute on function public.erfasse_historische_pachtberichtigung(text,bigint,jsonb,text) to authenticated;

create or replace function public.guard_abgeschlossene_pachtdaten()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if (tg_table_name='pachtverhaeltnis' and old.beendet_am is not null)
    or (tg_table_name='pachtverhaeltnis_beteiligung' and old.gueltig_bis is not null) then
   raise exception 'Abgeschlossene Pachtdaten bleiben Originale; eine Berichtigung ist ergänzend zu erfassen.' using errcode='42501';
 end if;
 return case when tg_op='DELETE' then old else new end;
end $$;
