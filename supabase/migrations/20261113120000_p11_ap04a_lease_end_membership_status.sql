-- P11 AP-04.1 / R06-R07: the contractual relation is the legal lease source.
-- Its end is recorded atomically with participation history and the passive
-- status of a principal tenant that has no further effective lease.

create table if not exists public.pachtende_audit (
  id bigint generated by default as identity primary key,
  pachtverhaeltnis_id bigint not null references public.pachtverhaeltnis(id),
  beendet_am date not null,
  begruendung text not null check (length(btrim(begruendung)) > 0),
  akteur_user_id uuid not null,
  erfasst_am timestamptz not null default now()
);
alter table public.pachtende_audit enable row level security;
revoke all on table public.pachtende_audit from public, anon, authenticated;

create or replace function public.beende_pachtverhaeltnis(
  p_pachtverhaeltnis_id bigint,
  p_beendet_am date,
  p_begruendung text
)
returns table (
  pachtverhaeltnis_id bigint,
  bereits_beendet boolean,
  passiv_gesetzte_hauptmitglieder bigint[]
)
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_actor uuid := auth.uid();
  v_relation public.pachtverhaeltnis%rowtype;
  v_reason text := nullif(btrim(p_begruendung), '');
  v_passive bigint[] := array[]::bigint[];
  v_member_id bigint;
begin
  if v_actor is null or not public.has_effective_permission(524288) then
    raise exception 'Keine Berechtigung zum Beenden eines Pachtverhältnisses.' using errcode = '42501';
  end if;
  if p_pachtverhaeltnis_id is null or p_pachtverhaeltnis_id <= 0 or p_beendet_am is null or v_reason is null then
    raise exception 'Pachtverhältnis, Enddatum und Begründung sind erforderlich.' using errcode = '22023';
  end if;
  if p_beendet_am > public.kgv_local_now()::date then
    raise exception 'Ein zukünftiges Pachtende wird erst am Wirksamkeitstag abgeschlossen.' using errcode = '23514';
  end if;
  select * into v_relation from public.pachtverhaeltnis where id=p_pachtverhaeltnis_id for update;
  if not found then raise exception 'Pachtverhältnis wurde nicht gefunden.' using errcode = 'P0002'; end if;
  if v_relation.beendet_am is not null then
    if v_relation.beendet_am = p_beendet_am then
      return query select v_relation.id, true, array[]::bigint[];
      return;
    end if;
    raise exception 'Das Pachtverhältnis wurde bereits an einem anderen Datum beendet.' using errcode = '23505';
  end if;
  if p_beendet_am < v_relation.urspruenglicher_pachtbeginn then
    raise exception 'Das Pachtende liegt vor dem Pachtbeginn.' using errcode = '23514';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('pachtverhaeltnis:parzelle:' || v_relation.parzelle_id::text, 0));

  update public.pachtverhaeltnis_beteiligung as b
     set gueltig_bis = p_beendet_am
   where b.pachtverhaeltnis_id=v_relation.id
     and b.gueltig_ab <= p_beendet_am
     and (b.gueltig_bis is null or b.gueltig_bis > p_beendet_am);
  update public.pachtverhaeltnis set beendet_am=p_beendet_am, beendigungsgrund='sonstiges' where id=v_relation.id;
  insert into public.pachtende_audit(pachtverhaeltnis_id,beendet_am,begruendung,akteur_user_id)
  values(v_relation.id,p_beendet_am,v_reason,v_actor);

  -- R06 applies to the principal tenant only. Co-tenants remain members and
  -- their membership relation is never deleted by ending this contract.
  for v_member_id in
    select distinct b.mitglied_id from public.pachtverhaeltnis_beteiligung b
    where b.pachtverhaeltnis_id=v_relation.id and b.rolle='hauptpaechter' and b.gueltig_ab<=p_beendet_am
  loop
    if not exists (
      select 1 from public.pachtverhaeltnis_beteiligung b
      join public.pachtverhaeltnis r on r.id=b.pachtverhaeltnis_id
      where b.mitglied_id=v_member_id and r.id<>v_relation.id
        and r.beendet_am is null and b.gueltig_ab<=p_beendet_am
        and (b.gueltig_bis is null or b.gueltig_bis>=p_beendet_am)
    ) then
      update public.mitglied set aktiv=false
      where id=v_member_id and aufnahme_status='aufgenommen' and mitglied_ende is null and aktiv=true;
      if found then v_passive := array_append(v_passive,v_member_id); end if;
    end if;
  end loop;
  return query select v_relation.id, false, v_passive;
end;
$$;
revoke all on function public.beende_pachtverhaeltnis(bigint,date,text) from public, anon;
grant execute on function public.beende_pachtverhaeltnis(bigint,date,text) to authenticated;
comment on function public.beende_pachtverhaeltnis(bigint,date,text) is
  'P11 AP-04.1: authorized, audited and idempotent legal lease ending; only a principal tenant without another effective lease becomes passive.';
