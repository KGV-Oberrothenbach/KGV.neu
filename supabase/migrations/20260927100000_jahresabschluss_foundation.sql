create or replace function public.validate_jahresabschluss_rechnung_zuordnung()
returns trigger
language plpgsql
as $$
declare
    v_rechnung_id bigint := coalesce(new.rechnung_id, old.rechnung_id);
    v_gesamtbetrag numeric(12,2);
    v_zugeordnet numeric(12,2);
    v_kuerzel text;
begin
    select r.gesamtbetrag into v_gesamtbetrag
    from public.jahresabschluss_rechnung r
    where r.id = v_rechnung_id;

    select coalesce(sum(z.betrag), 0) into v_zugeordnet
    from public.jahresabschluss_rechnung_zuordnung z
    where z.rechnung_id = v_rechnung_id
      and z.id <> coalesce(old.id, -1);

    if tg_op <> 'DELETE' then
        v_zugeordnet := v_zugeordnet + new.betrag;

        select kuerzel into v_kuerzel
        from public.umlageart
        where id = new.umlageart_id;

        if v_kuerzel = 'EINZEL' and new.parzelle_id is null and new.mitglied_id is null then
            raise exception 'EINZEL-Zuordnungen benötigen eine Parzelle oder ein Mitglied.';
        end if;
    end if;

    if v_zugeordnet > v_gesamtbetrag then
        raise exception 'Die Zuordnungssumme (%) übersteigt den Rechnungsbetrag (%).', v_zugeordnet, v_gesamtbetrag;
    end if;

    if tg_op = 'DELETE' then
        return old;
    end if;

    return new;
end;
$$;

drop trigger if exists trg_validate_jahresabschluss_rechnung_zuordnung on public.jahresabschluss_rechnung_zuordnung;
create trigger trg_validate_jahresabschluss_rechnung_zuordnung
before insert or update or delete on public.jahresabschluss_rechnung_zuordnung
for each row execute function public.validate_jahresabschluss_rechnung_zuordnung();

create or replace function public.prevent_abgeschlossener_jahresabschluss_change()
returns trigger
language plpgsql
as $$
begin
    if old.status = 'abgeschlossen' then
        raise exception 'Ein abgeschlossener Jahresabschluss ist unveränderlich. Verwenden Sie einen Korrekturabschluss.';
    end if;
    return new;
end;
$$;

drop trigger if exists trg_prevent_abgeschlossener_jahresabschluss_change on public.jahresabschluss;
create trigger trg_prevent_abgeschlossener_jahresabschluss_change
before update or delete on public.jahresabschluss
for each row execute function public.prevent_abgeschlossener_jahresabschluss_change();

