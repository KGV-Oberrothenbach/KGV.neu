create table if not exists public.kostenart (
    id bigint generated by default as identity primary key,
    bezeichnung text not null,
    beschreibung text,
    aktiv boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint kostenart_bezeichnung_uq unique (bezeichnung)
);

create table if not exists public.umlageart (
    id bigint generated by default as identity primary key,
    kuerzel text not null,
    bezeichnung text not null,
    verteilung text not null,
    aktiv boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint umlageart_kuerzel_uq unique (kuerzel),
    constraint umlageart_verteilung_chk check (verteilung in (
        'pro_mitglied', 'pro_flaeche_und_tag', 'anschluss_und_tag',
        'verbrauch', 'einzel', 'keine'
    ))
);

