create table if not exists public.jahresabschluss (
    id bigint generated by default as identity primary key,
    saison_id integer not null references public.saison(id),
    status text not null default 'in_bearbeitung',
    berechnung_version text not null default '1',
    bemerkung text,
    erstellt_am timestamp with time zone not null default now(),
    erstellt_von bigint references public.mitglied(id),
    abgeschlossen_am timestamp with time zone,
    abgeschlossen_von bigint references public.mitglied(id),
    constraint jahresabschluss_saison_uq unique (saison_id),
    constraint jahresabschluss_status_chk check (status in ('in_bearbeitung', 'berechnet', 'geprueft', 'abgeschlossen')),
    constraint jahresabschluss_abschluss_chk check (
        (status = 'abgeschlossen' and abgeschlossen_am is not null and abgeschlossen_von is not null)
        or status <> 'abgeschlossen'
    )
);

create table if not exists public.jahresabschluss_rechnung (
    id bigint generated by default as identity primary key,
    saison_id integer not null references public.saison(id),
    lieferant text not null,
