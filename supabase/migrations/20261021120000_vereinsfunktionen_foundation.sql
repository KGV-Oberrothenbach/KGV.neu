-- V2 foundation only. Existing Impressum slots remain the productive compatibility path.

create table if not exists public.vereinsfunktion (
    id bigint generated by default as identity primary key,
    schluessel text not null unique,
    bezeichnung text not null,
    aktiv boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ck_vereinsfunktion_schluessel_nonempty check (btrim(schluessel) <> ''),
    constraint ck_vereinsfunktion_bezeichnung_nonempty check (btrim(bezeichnung) <> '')
);

create table if not exists public.vereinsfunktion_besetzung (
    id bigint generated by default as identity primary key,
    vereinsfunktion_id bigint not null references public.vereinsfunktion(id) on delete restrict,
    mitglied_id bigint not null references public.mitglied(id) on delete restrict,
    gueltig_ab date not null,
    gueltig_bis date null,
    sort_order smallint not null default 10,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ck_vereinsfunktion_besetzung_zeitraum check (gueltig_bis is null or gueltig_bis >= gueltig_ab)
);

create table if not exists public.vereinsfunktion_verwendung (
    id bigint generated by default as identity primary key,
    vereinsfunktion_id bigint not null references public.vereinsfunktion(id) on delete restrict,
    verwendungszweck text not null,
    sort_order smallint not null default 10,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ck_vereinsfunktion_verwendung_zweck_nonempty check (btrim(verwendungszweck) <> '')
);

create index if not exists ix_vereinsfunktion_besetzung_aktuell
    on public.vereinsfunktion_besetzung (vereinsfunktion_id, gueltig_ab, gueltig_bis, sort_order);
create index if not exists ix_vereinsfunktion_besetzung_mitglied
    on public.vereinsfunktion_besetzung (mitglied_id, gueltig_ab, gueltig_bis);
create index if not exists ix_vereinsfunktion_verwendung
    on public.vereinsfunktion_verwendung (verwendungszweck, sort_order, vereinsfunktion_id);

create or replace function public.set_updated_at_vereinsfunktion()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_vereinsfunktion_updated_at on public.vereinsfunktion;
create trigger trg_vereinsfunktion_updated_at before update on public.vereinsfunktion
for each row execute function public.set_updated_at_vereinsfunktion();
drop trigger if exists trg_vereinsfunktion_besetzung_updated_at on public.vereinsfunktion_besetzung;
create trigger trg_vereinsfunktion_besetzung_updated_at before update on public.vereinsfunktion_besetzung
for each row execute function public.set_updated_at_vereinsfunktion();
drop trigger if exists trg_vereinsfunktion_verwendung_updated_at on public.vereinsfunktion_verwendung;
create trigger trg_vereinsfunktion_verwendung_updated_at before update on public.vereinsfunktion_verwendung
for each row execute function public.set_updated_at_vereinsfunktion();

-- Compatibility import: current slots define existing functions and the sole
-- currently evidenced use, Impressum. The date records the migration baseline,
-- not an invented historical start of office.
insert into public.vereinsfunktion (schluessel, bezeichnung, aktiv)
select s.slot_key, s.funktion, true
from public.impressum_funktion_slot s
on conflict (schluessel) do nothing;

insert into public.vereinsfunktion_verwendung (vereinsfunktion_id, verwendungszweck, sort_order)
select f.id, 'impressum', s.sort_order
from public.impressum_funktion_slot s
join public.vereinsfunktion f on f.schluessel = s.slot_key
where not exists (
    select 1 from public.vereinsfunktion_verwendung v
    where v.vereinsfunktion_id = f.id and v.verwendungszweck = 'impressum'
);

insert into public.vereinsfunktion_besetzung
    (vereinsfunktion_id, mitglied_id, gueltig_ab, gueltig_bis, sort_order)
select f.id, s.mitglied_id, current_date, null, s.sort_order
from public.impressum_funktion_slot s
join public.vereinsfunktion f on f.schluessel = s.slot_key
where s.mitglied_id is not null
  and not exists (
      select 1 from public.vereinsfunktion_besetzung b
      where b.vereinsfunktion_id = f.id
        and b.mitglied_id = s.mitglied_id
        and b.gueltig_bis is null
  );

alter table public.vereinsfunktion enable row level security;
alter table public.vereinsfunktion_besetzung enable row level security;
alter table public.vereinsfunktion_verwendung enable row level security;

create policy vereinsfunktion_admin_full on public.vereinsfunktion
    to authenticated using (public.is_admin_or_vorstand()) with check (public.is_admin_or_vorstand());
create policy vereinsfunktion_besetzung_admin_full on public.vereinsfunktion_besetzung
    to authenticated using (public.is_admin_or_vorstand()) with check (public.is_admin_or_vorstand());
create policy vereinsfunktion_verwendung_admin_full on public.vereinsfunktion_verwendung
    to authenticated using (public.is_admin_or_vorstand()) with check (public.is_admin_or_vorstand());

-- Future Impressum readers may see only active functions, their current
-- assignments and the established impressum use. Historical assignments and
-- every other future use remain limited to admin/vorstand or service_role.
create policy vereinsfunktion_impressum_select_authenticated on public.vereinsfunktion
    for select to authenticated
    using (
        aktiv
        and exists (
            select 1 from public.vereinsfunktion_verwendung v
            where v.vereinsfunktion_id = id
              and v.verwendungszweck = 'impressum'
        )
    );
create policy vereinsfunktion_verwendung_impressum_select_authenticated on public.vereinsfunktion_verwendung
    for select to authenticated
    using (verwendungszweck = 'impressum');
create policy vereinsfunktion_besetzung_impressum_select_authenticated on public.vereinsfunktion_besetzung
    for select to authenticated
    using (
        gueltig_ab <= current_date
        and (gueltig_bis is null or gueltig_bis >= current_date)
        and exists (
            select 1
            from public.vereinsfunktion f
            join public.vereinsfunktion_verwendung v on v.vereinsfunktion_id = f.id
            where f.id = vereinsfunktion_besetzung.vereinsfunktion_id
              and f.aktiv
              and v.verwendungszweck = 'impressum'
        )
    );

grant all on table public.vereinsfunktion, public.vereinsfunktion_besetzung, public.vereinsfunktion_verwendung to authenticated, service_role;
grant usage, select on sequence public.vereinsfunktion_id_seq, public.vereinsfunktion_besetzung_id_seq, public.vereinsfunktion_verwendung_id_seq to authenticated, service_role;
