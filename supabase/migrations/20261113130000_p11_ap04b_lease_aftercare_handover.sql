-- P11 AP-04.2: aftercare belongs to a completed legal lease, not to the
-- operational parcel assignment. Existing parcel protocols are reused.
create table public.pacht_nachsorge (
 id bigint generated by default as identity primary key,
 pachtverhaeltnis_id bigint not null unique references public.pachtverhaeltnis(id),
 parzelle_id bigint not null references public.parzelle(id),
 beginnt_am date not null, endet_am date not null,
 beendet_am date null, beendigungsgrund text null,
 beschlossen_von uuid null, beschlossen_am timestamptz null,
 erstellt_von uuid not null, erstellt_am timestamptz not null default now(),
 check (endet_am >= beginnt_am and endet_am <= beginnt_am + interval '2 years')
);
alter table public.pacht_nachsorge enable row level security;
revoke all on public.pacht_nachsorge from public,anon,authenticated;
alter table public.parzellen_protokoll add column if not exists pachtverhaeltnis_id bigint references public.pachtverhaeltnis(id);
create unique index if not exists ux_pacht_nachsorge_rueckgabe on public.parzellen_protokoll(pachtverhaeltnis_id) where protokoll_typ='rueckgabe' and status='abgeschlossen';

create or replace function public.erstelle_pacht_nachsorge(p_pachtverhaeltnis_id bigint,p_endet_am date)
returns bigint language plpgsql security definer set search_path=public,pg_temp as $$
declare r public.pachtverhaeltnis%rowtype; x bigint; caller uuid:=auth.uid();
begin
 if caller is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für Nachsorge.' using errcode='42501'; end if;
 select * into r from public.pachtverhaeltnis where id=p_pachtverhaeltnis_id for update;
 if not found or r.beendet_am is null then raise exception 'Nachsorge setzt ein rechtlich beendetes Pachtverhältnis voraus.' using errcode='23514'; end if;
 if p_endet_am is null or p_endet_am<r.beendet_am or p_endet_am>r.beendet_am+interval '2 years' then raise exception 'Unzulässiges Nachsorgeende.' using errcode='23514'; end if;
 insert into public.pacht_nachsorge(pachtverhaeltnis_id,parzelle_id,beginnt_am,endet_am,erstellt_von) values(r.id,r.parzelle_id,r.beendet_am,p_endet_am,caller) returning id into x;
 return x;
end $$;
