-- PV-DB1b: Fachliche Identität von Pachtverhältnissen und ihren Vertragsfassungen.
-- Bestandstabellen und Bestandsdaten bleiben in dieser Migration absichtlich unverändert.

create table public.pachtverhaeltnis (
  id bigint generated by default as identity primary key,
  parzelle_id bigint not null references public.parzelle(id) on delete restrict,
  urspruenglicher_pachtbeginn date,
  beendet_am date,
  beendigungsgrund text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint pachtverhaeltnis_beendigungsgrund_chk check (
    beendigungsgrund is null or beendigungsgrund in ('kuendigung', 'tod', 'wechsel', 'sonstiges')
  ),
  constraint pachtverhaeltnis_zeitraum_chk check (
    beendet_am is null or urspruenglicher_pachtbeginn is null or beendet_am >= urspruenglicher_pachtbeginn
  ),
  constraint pachtverhaeltnis_aktiver_endegrund_chk check (
    beendet_am is not null or beendigungsgrund is null
  )
);

create unique index ux_pachtverhaeltnis_eins_aktiv_pro_parzelle
  on public.pachtverhaeltnis(parzelle_id)
  where beendet_am is null;
create index ix_pachtverhaeltnis_parzelle_id on public.pachtverhaeltnis(parzelle_id);

create table public.pachtverhaeltnis_beteiligung (
  id bigint generated by default as identity primary key,
  pachtverhaeltnis_id bigint not null references public.pachtverhaeltnis(id) on delete restrict,
  mitglied_id bigint not null references public.mitglied(id) on delete restrict,
  rolle text not null,
  gueltig_ab date not null,
  gueltig_bis date,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint pachtverhaeltnis_beteiligung_rolle_chk check (rolle in ('hauptpaechter', 'mitpaechter')),
  constraint pachtverhaeltnis_beteiligung_zeitraum_chk check (gueltig_bis is null or gueltig_bis >= gueltig_ab)
);

create unique index ux_pachtverhaeltnis_beteiligung_ein_aktiv_pro_mitglied
  on public.pachtverhaeltnis_beteiligung(pachtverhaeltnis_id, mitglied_id)
  where gueltig_bis is null;
create unique index ux_pachtverhaeltnis_beteiligung_ein_aktiver_hauptpaechter
  on public.pachtverhaeltnis_beteiligung(pachtverhaeltnis_id)
  where rolle = 'hauptpaechter' and gueltig_bis is null;
create index ix_pachtverhaeltnis_beteiligung_pachtverhaeltnis_id on public.pachtverhaeltnis_beteiligung(pachtverhaeltnis_id);
create index ix_pachtverhaeltnis_beteiligung_mitglied_id on public.pachtverhaeltnis_beteiligung(mitglied_id);

create table public.pachtvertragsfassung (
  id bigint generated by default as identity primary key,
  pachtverhaeltnis_id bigint not null references public.pachtverhaeltnis(id) on delete restrict,
  dokument_id bigint not null references public.dokument(id) on delete restrict,
  fassungstyp text not null,
  vertragsdatum date,
  wirksam_ab date,
  vorheriges_vertragsdatum date,
  vorgaenger_fassung_id bigint references public.pachtvertragsfassung(id) on delete restrict,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint pachtvertragsfassung_dokument_uq unique (dokument_id),
  constraint pachtvertragsfassung_typ_chk check (fassungstyp in ('erstvertrag', 'neufassung', 'import')),
  constraint pachtvertragsfassung_vorgaenger_chk check (vorgaenger_fassung_id is null or vorgaenger_fassung_id <> id),
  constraint pachtvertragsfassung_neufassung_chk check (fassungstyp <> 'neufassung' or vorheriges_vertragsdatum is not null)
);

create index ix_pachtvertragsfassung_pachtverhaeltnis_id on public.pachtvertragsfassung(pachtverhaeltnis_id);
create index ix_pachtvertragsfassung_vertragsdatum on public.pachtvertragsfassung(vertragsdatum);
create index ix_pachtvertragsfassung_wirksam_ab on public.pachtvertragsfassung(wirksam_ab);

comment on table public.pachtverhaeltnis is 'Dauerhafte fachliche Identität eines Pachtverhältnisses; parzellen_belegung bleibt vorerst davon getrennt.';
comment on column public.pachtverhaeltnis.urspruenglicher_pachtbeginn is 'Erstmaliger Beginn des Pachtverhältnisses; nicht mit Vertragsdatum oder vorherigem Vertragsdatum gleichzusetzen.';
comment on table public.pachtvertragsfassung is 'Historische Vertragsfassungen eines Pachtverhältnisses; Provenance folgt über dokument.';
comment on column public.pachtvertragsfassung.fassungstyp is 'erstvertrag für den ersten neu erzeugten Vertrag, neufassung für einen Folgevertrag, import für historischen Bestand.';
comment on column public.pachtvertragsfassung.vertragsdatum is 'Datum des tatsächlich abgeschlossenen oder signierten Vertrags; nie das Preview-Datum.';
comment on column public.pachtvertragsfassung.wirksam_ab is 'Fachlicher Beginn der Wirksamkeit dieser Vertragsfassung; nicht der ursprüngliche Pachtbeginn.';
comment on column public.pachtvertragsfassung.vorheriges_vertragsdatum is 'Im Neufassungsworkflow angegebener vorheriger Vertragsstand; nicht der ursprüngliche Pachtbeginn.';
comment on column public.pachtvertragsfassung.vorgaenger_fassung_id is 'Explizite Vorgängerfassung; kann bei nicht importierbarem historischem Vorgänger leer bleiben.';

alter table public.pachtverhaeltnis enable row level security;
alter table public.pachtverhaeltnis_beteiligung enable row level security;
alter table public.pachtvertragsfassung enable row level security;

create policy pachtverhaeltnis_admin_vorstand_select on public.pachtverhaeltnis for select to authenticated using (
  exists (select 1 from public.current_app_user_context() c where c.role in ('admin', 'vorstand'))
);
create policy pachtverhaeltnis_beteiligung_admin_vorstand_select on public.pachtverhaeltnis_beteiligung for select to authenticated using (
  exists (select 1 from public.current_app_user_context() c where c.role in ('admin', 'vorstand'))
);
create policy pachtvertragsfassung_admin_vorstand_select on public.pachtvertragsfassung for select to authenticated using (
  exists (select 1 from public.current_app_user_context() c where c.role in ('admin', 'vorstand'))
);

revoke all on table public.pachtverhaeltnis, public.pachtverhaeltnis_beteiligung, public.pachtvertragsfassung from public, anon, authenticated;
grant select on table public.pachtverhaeltnis, public.pachtverhaeltnis_beteiligung, public.pachtvertragsfassung to authenticated;
grant all on table public.pachtverhaeltnis, public.pachtverhaeltnis_beteiligung, public.pachtvertragsfassung to service_role;
revoke all on sequence public.pachtverhaeltnis_id_seq, public.pachtverhaeltnis_beteiligung_id_seq, public.pachtvertragsfassung_id_seq from public, anon, authenticated;
grant usage, select on sequence public.pachtverhaeltnis_id_seq, public.pachtverhaeltnis_beteiligung_id_seq, public.pachtvertragsfassung_id_seq to service_role;
