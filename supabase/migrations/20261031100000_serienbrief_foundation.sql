-- Serienbrief G2: persistente Vorlagen und metadata-getriebener Export-Datenvertrag.
-- Es werden bewusst keine Serienbriefläufe, PDFs, Dokumente oder Versandvorgänge erzeugt.

alter table public.app_export_definition
  add column if not exists serienbrief_erlaubt boolean not null default false,
  add column if not exists serienbrief_mitglied_id_feld text,
  add column if not exists serienbrief_parzelle_id_feld text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.app_export_definition'::regclass
      and conname = 'app_export_definition_serienbrief_mitglied_id_chk'
  ) then
    alter table public.app_export_definition
      add constraint app_export_definition_serienbrief_mitglied_id_chk check (
        not serienbrief_erlaubt
        or nullif(btrim(serienbrief_mitglied_id_feld), '') is not null
      );
  end if;
end;
$$;

comment on column public.app_export_definition.serienbrief_erlaubt is
  'Explizite Metadatenfreigabe für Serienbriefe. Standardmäßig false; keine Ableitung aus Export-Key oder Quellentyp.';
comment on column public.app_export_definition.serienbrief_mitglied_id_feld is
  'Technischer Feldschlüssel im Roh-Ergebnisvertrag, der die stabile mitglied_id enthält; keine sichtbare Exportspalte erforderlich.';
comment on column public.app_export_definition.serienbrief_parzelle_id_feld is
  'Optionaler technischer Feldschlüssel im Roh-Ergebnisvertrag für eine eindeutige parzelle_id; keine sichtbare Exportspalte erforderlich.';

alter table public.app_export_column_definition
  add column if not exists serienbrief_freigegeben boolean not null default false,
  add column if not exists serienbrief_gruppe text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.app_export_column_definition'::regclass
      and conname = 'app_export_column_definition_serienbrief_technische_id_chk'
  ) then
    alter table public.app_export_column_definition
      add constraint app_export_column_definition_serienbrief_technische_id_chk check (
        not serienbrief_freigegeben
        or column_key not in ('mitglied_id', 'parzelle_id')
      );
  end if;
end;
$$;

comment on column public.app_export_column_definition.serienbrief_freigegeben is
  'Nur explizit freigegebene fachliche Exportfelder dürfen später im Serienbrief-Vorlageneditor angeboten werden.';
comment on column public.app_export_column_definition.serienbrief_gruppe is
  'Optionale reine Darstellungsgruppe für Serienbrieffelder, z. B. Mitglied, Parzelle, Zähler, Saison, Abrechnung oder Sonstiges.';

create table if not exists public.serienbrief_vorlage (
  id bigint generated by default as identity primary key,
  name text not null,
  betreff_vorlage text not null default '',
  anrede_modus text not null default 'briefanrede'
    check (anrede_modus in ('briefanrede')),
  html_inhalt text not null default '',
  grundlayout_template_key text not null default 'briefbogen-allgemein',
  grundlayout_version text not null default 'v2',
  aktiv boolean not null default true,
  erstellt_am timestamptz not null default now(),
  erstellt_von uuid references auth.users(id) on delete set null,
  geaendert_am timestamptz not null default now(),
  geaendert_von uuid references auth.users(id) on delete set null,
  constraint serienbrief_vorlage_name_chk check (length(btrim(name)) > 0),
  constraint serienbrief_vorlage_layout_chk check (
    length(btrim(grundlayout_template_key)) > 0
    and length(btrim(grundlayout_version)) > 0
  )
);

create unique index if not exists ux_serienbrief_vorlage_name_ci
  on public.serienbrief_vorlage (lower(btrim(name)));

create table if not exists public.serienbrief_vorlage_exportfeld (
  serienbrief_vorlage_id bigint not null
    references public.serienbrief_vorlage(id) on delete cascade,
  feldschluessel text not null,
  primary key (serienbrief_vorlage_id, feldschluessel),
  constraint serienbrief_vorlage_exportfeld_schluessel_chk check (length(btrim(feldschluessel)) > 0)
);

create table if not exists public.serienbrief_vorlage_freifeld (
  id bigint generated by default as identity primary key,
  serienbrief_vorlage_id bigint not null
    references public.serienbrief_vorlage(id) on delete cascade,
  schluessel text not null,
  anzeigename text not null,
  typ text not null check (typ in ('text', 'date', 'number')),
  pflicht boolean not null default false,
  sortierung integer not null default 0,
  constraint serienbrief_vorlage_freifeld_schluessel_chk check (length(btrim(schluessel)) > 0),
  constraint serienbrief_vorlage_freifeld_anzeigename_chk check (length(btrim(anzeigename)) > 0),
  constraint serienbrief_vorlage_freifeld_uq unique (serienbrief_vorlage_id, schluessel)
);

create index if not exists ix_serienbrief_vorlage_freifeld_sortierung
  on public.serienbrief_vorlage_freifeld (serienbrief_vorlage_id, sortierung, id);

create or replace function public.set_serienbrief_vorlage_audit_fields()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.erstellt_von := auth.uid();
      new.geaendert_von := auth.uid();
    end if;
    return new;
  end if;

  new.erstellt_am := old.erstellt_am;
  new.erstellt_von := old.erstellt_von;
  new.geaendert_am := now();
  if auth.uid() is not null then
    new.geaendert_von := auth.uid();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_serienbrief_vorlage_audit_fields on public.serienbrief_vorlage;
create trigger trg_serienbrief_vorlage_audit_fields
before insert or update on public.serienbrief_vorlage
for each row execute function public.set_serienbrief_vorlage_audit_fields();

