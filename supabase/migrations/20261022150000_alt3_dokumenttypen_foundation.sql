comment on table public.dokumenttyp_wirkung is
    'Fachliche Nachweis- und Validierungswirkungen eines allgemeinen Dokumenttyps; niemals aus Code oder Bezeichnung ableiten.';
comment on table public.dokument_wartungsvertrag_zuordnung is
    'Neutrale Dokument-zu-Wartungsvertragszuordnung für künftige Import- und Fachprozesse; getrennt von Prepared-Contract-Provenance.';
