-- Persistent, revision-bound individual signatures for prepared contracts.
-- This migration deliberately does not infer a signature plan from document types.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('prepared-contract-signatures', 'prepared-contract-signatures', false, 1048576, array['image/png'])
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
create table public.prepared_contract_signatur (
    id bigint generated by default as identity primary key,
    kommunikationsvorgang_id bigint not null
        references public.kommunikationsvorgang(id) on delete restrict,
    signatur_revision integer not null check (signatur_revision >= 1),
    signatur_schluessel text not null check (btrim(signatur_schluessel) <> ''),
    sort_order smallint not null,
    pflicht boolean not null,
    status text not null default 'offen'
        check (status in ('offen', 'unterschrieben')),
    unterzeichner_typ text not null check (btrim(unterzeichner_typ) <> ''),
    mitglied_id bigint references public.mitglied(id) on delete restrict,
    unterzeichner_name_snapshot text,
    vereinsfunktion_id bigint references public.vereinsfunktion(id) on delete restrict,
    vereinsfunktion_bezeichnung_snapshot text,
    vereinsfunktion_besetzung_id bigint
        references public.vereinsfunktion_besetzung(id) on delete restrict,
    vertretung_id bigint references public.vereinsfunktion_vertretung(id) on delete restrict,
    vertretene_vereinsfunktion_id bigint references public.vereinsfunktion(id) on delete restrict,
    vertretene_funktion_bezeichnung_snapshot text,
    vertretene_besetzung_id bigint
        references public.vereinsfunktion_besetzung(id) on delete restrict,
    storage_bucket text,
    storage_path text,
    signatur_sha256 text,
    unterzeichnet_am timestamptz,
    unterzeichnet_von_auth_user_id uuid references auth.users(id) on delete restrict,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint prepared_contract_signatur_position_uq
        unique (kommunikationsvorgang_id, signatur_revision, signatur_schluessel),
    constraint prepared_contract_signatur_storage_chk check (
        (status = 'offen'
            and storage_bucket is null and storage_path is null and signatur_sha256 is null
            and unterzeichnet_am is null and unterzeichnet_von_auth_user_id is null)
        or
        (status = 'unterschrieben'
            and storage_bucket = 'prepared-contract-signatures'
            and storage_path ~ '^[0-9]+/[0-9]+/[^/]+/[0-9a-fA-F-]{36}[.]png$'
            and signatur_sha256 ~ '^[0-9a-f]{64}$'
            and unterzeichnet_am is not null and unterzeichnet_von_auth_user_id is not null)
    ),
    constraint prepared_contract_signatur_board_snapshot_chk check (
        unterzeichner_typ <> 'vereinsunterzeichner'
        or (
            status = 'offen'
            or (
                mitglied_id is not null
                and nullif(btrim(unterzeichner_name_snapshot), '') is not null
                and vereinsfunktion_id is not null
                and nullif(btrim(vereinsfunktion_bezeichnung_snapshot), '') is not null
                and vereinsfunktion_besetzung_id is not null
                and (
                    (vertretung_id is null
                        and vertretene_vereinsfunktion_id is null
                        and vertretene_funktion_bezeichnung_snapshot is null
                        and vertretene_besetzung_id is null)
                    or
                    (vertretung_id is not null
                        and vertretene_vereinsfunktion_id is not null
                        and nullif(btrim(vertretene_funktion_bezeichnung_snapshot), '') is not null
                        and vertretene_besetzung_id is not null)
                )
            )
        )
    )
);
