create or replace function public.guard_prepared_contract_signatur()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_vorgang public.kommunikationsvorgang%rowtype;
begin
    select * into v_vorgang
    from public.kommunikationsvorgang
    where id = new.kommunikationsvorgang_id;

    if not found
       or v_vorgang.vorgangstyp <> 'vertrag_signatur'
       or v_vorgang.signatur_revision is null
       or new.signatur_revision <> v_vorgang.signatur_revision then
        raise exception 'Signaturposition passt nicht zur eingefrorenen Vertragsrevision.' using errcode = '23514';
    end if;

    if tg_op = 'INSERT' then
        if v_vorgang.status <> 'zur_signatur' then
            raise exception 'Signaturpositionen dürfen nur für einen Vorgang zur Signatur angelegt werden.' using errcode = '23514';
        end if;
        return new;
    end if;

    if old.status = 'unterschrieben' then
        raise exception 'Unterschriebene Signaturpositionen sind unveränderlich.' using errcode = '55000';
    end if;

    if new.kommunikationsvorgang_id is distinct from old.kommunikationsvorgang_id
       or new.signatur_revision is distinct from old.signatur_revision
       or new.signatur_schluessel is distinct from old.signatur_schluessel
       or new.sort_order is distinct from old.sort_order
       or new.pflicht is distinct from old.pflicht
       or new.unterzeichner_typ is distinct from old.unterzeichner_typ then
        raise exception 'Eine angelegte Signaturposition darf nicht umdefiniert werden.' using errcode = '55000';
    end if;

    if old.status = 'offen' and new.status <> 'unterschrieben' then
        raise exception 'Eine offene Signaturposition darf nur als unterschrieben gespeichert werden.' using errcode = '23514';
    end if;

    if v_vorgang.status <> 'zur_signatur' then
        raise exception 'Signaturen dürfen nur für einen Vorgang im Status zur_signatur gespeichert werden.' using errcode = '23514';
    end if;

    new.updated_at := now();
    return new;
end;
$$;
create or replace function public.prevent_delete_signed_prepared_contract_signatur()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if old.status = 'unterschrieben' then
        raise exception 'Unterschriebene Signaturpositionen dürfen nicht gelöscht werden.' using errcode = '55000';
    end if;
    return old;
end;
$$;
