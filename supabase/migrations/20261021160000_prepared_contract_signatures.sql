create or replace function public.vereinsfunktion_vertragsunterzeichner(p_stichtag date default current_date)
returns table (
    mitglied_id bigint,
    unterzeichner_name text,
    berechtigungsart text,
    vereinsfunktion_id bigint,
    vereinsfunktion_bezeichnung text,
    vereinsfunktion_besetzung_id bigint,
    vertretung_id bigint,
    vertretene_vereinsfunktion_id bigint,
    vertretene_funktion_bezeichnung text,
    vertretene_besetzung_id bigint,
    verwendungszweck_sort_order smallint,
    funktions_sort_order smallint,
    besetzung_sort_order smallint
)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
    with direkte_berechtigung as (
        select
            b.mitglied_id,
            nullif(btrim(concat_ws(' ', m.vorname, m.name)), '') as unterzeichner_name,
            'direkt'::text as berechtigungsart,
            f.id as vereinsfunktion_id,
            f.bezeichnung as vereinsfunktion_bezeichnung,
            b.id as vereinsfunktion_besetzung_id,
            null::bigint as vertretung_id,
            null::bigint as vertretene_vereinsfunktion_id,
            null::text as vertretene_funktion_bezeichnung,
            null::bigint as vertretene_besetzung_id,
            v.sort_order as verwendungszweck_sort_order,
            0::smallint as funktions_sort_order,
            b.sort_order as besetzung_sort_order
        from public.vereinsfunktion_verwendung v
        join public.vereinsfunktion f on f.id = v.vereinsfunktion_id and f.aktiv
        join public.vereinsfunktion_besetzung b on b.vereinsfunktion_id = f.id
        join public.mitglied m on m.id = b.mitglied_id
        where v.verwendungszweck = 'vertragsunterzeichnung'
          and b.gueltig_ab <= p_stichtag
          and (b.gueltig_bis is null or b.gueltig_bis >= p_stichtag)
    ), vertretungsberechtigung as (
        select
            eigene_besetzung.mitglied_id,
            nullif(btrim(concat_ws(' ', m.vorname, m.name)), '') as unterzeichner_name,
            'vertretung'::text as berechtigungsart,
            eigene_funktion.id as vereinsfunktion_id,
            eigene_funktion.bezeichnung as vereinsfunktion_bezeichnung,
            eigene_besetzung.id as vereinsfunktion_besetzung_id,
            vertretung.id as vertretung_id,
            vertretene_funktion.id as vertretene_vereinsfunktion_id,
            vertretene_funktion.bezeichnung as vertretene_funktion_bezeichnung,
            vertretene_besetzung.id as vertretene_besetzung_id,
            verwendung.sort_order as verwendungszweck_sort_order,
            eigene_besetzung.sort_order as funktions_sort_order,
            vertretene_besetzung.sort_order as besetzung_sort_order
        from public.vereinsfunktion_vertretung vertretung
        join public.vereinsfunktion_besetzung eigene_besetzung on eigene_besetzung.id = vertretung.vertreter_besetzung_id
        join public.vereinsfunktion eigene_funktion on eigene_funktion.id = eigene_besetzung.vereinsfunktion_id and eigene_funktion.aktiv
        join public.vereinsfunktion_besetzung vertretene_besetzung on vertretene_besetzung.id = vertretung.vertretene_besetzung_id
        join public.vereinsfunktion vertretene_funktion on vertretene_funktion.id = vertretene_besetzung.vereinsfunktion_id and vertretene_funktion.aktiv
        join public.vereinsfunktion_verwendung verwendung on verwendung.vereinsfunktion_id = vertretene_funktion.id
        join public.mitglied m on m.id = eigene_besetzung.mitglied_id
        where verwendung.verwendungszweck = 'vertragsunterzeichnung'
          and vertretung.gueltig_ab <= p_stichtag
          and (vertretung.gueltig_bis is null or vertretung.gueltig_bis >= p_stichtag)
          and eigene_besetzung.gueltig_ab <= p_stichtag
          and (eigene_besetzung.gueltig_bis is null or eigene_besetzung.gueltig_bis >= p_stichtag)
          and vertretene_besetzung.gueltig_ab <= p_stichtag
          and (vertretene_besetzung.gueltig_bis is null or vertretene_besetzung.gueltig_bis >= p_stichtag)
    )
    select * from direkte_berechtigung
    union all
    select * from vertretungsberechtigung
    order by verwendungszweck_sort_order, funktions_sort_order, besetzung_sort_order, vereinsfunktion_id, vereinsfunktion_besetzung_id, vertretung_id nulls first;
$$;
-- Positions are supplied by the application-owned plan. This function never
-- derives keys from a document type and is safe to call repeatedly.
create or replace function public.ensure_prepared_contract_signatur_position(
    p_kommunikationsvorgang_id bigint,
    p_signatur_revision integer,
    p_signatur_schluessel text,
    p_sort_order smallint,
    p_pflicht boolean,
    p_unterzeichner_typ text,
    p_mitglied_id bigint default null,
    p_unterzeichner_name_snapshot text default null
)
returns public.prepared_contract_signatur
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_vorgang public.kommunikationsvorgang%rowtype;
    v_position public.prepared_contract_signatur%rowtype;
begin
    if not public.is_admin_or_vorstand() then
        raise exception 'Nur administrative Vertragsbearbeitung darf Signaturpositionen vorbereiten.' using errcode = '42501';
    end if;

    select * into v_vorgang from public.kommunikationsvorgang
    where id = p_kommunikationsvorgang_id for update;
    if not found or v_vorgang.vorgangstyp <> 'vertrag_signatur'
       or v_vorgang.status <> 'zur_signatur'
       or v_vorgang.signatur_revision is distinct from p_signatur_revision then
        raise exception 'Der Vertragsvorgang ist nicht für diese Signaturrevision vorbereitet.' using errcode = '23514';
    end if;

    select * into v_position from public.prepared_contract_signatur
    where kommunikationsvorgang_id = p_kommunikationsvorgang_id
      and signatur_revision = p_signatur_revision
      and signatur_schluessel = p_signatur_schluessel
    for update;

    if found then
        if v_position.sort_order <> p_sort_order or v_position.pflicht <> p_pflicht
           or v_position.unterzeichner_typ <> p_unterzeichner_typ
           or v_position.mitglied_id is distinct from p_mitglied_id
           or v_position.unterzeichner_name_snapshot is distinct from nullif(btrim(p_unterzeichner_name_snapshot), '') then
            raise exception 'Eine bestehende Signaturposition stimmt nicht mit dem angeforderten Signaturplan überein.' using errcode = '23514';
        end if;
        return v_position;
    end if;

    insert into public.prepared_contract_signatur (
        kommunikationsvorgang_id, signatur_revision, signatur_schluessel,
        sort_order, pflicht, unterzeichner_typ, mitglied_id, unterzeichner_name_snapshot
    ) values (
        p_kommunikationsvorgang_id, p_signatur_revision, p_signatur_schluessel,
        p_sort_order, p_pflicht, p_unterzeichner_typ, p_mitglied_id,
        nullif(btrim(p_unterzeichner_name_snapshot), '')
    ) returning * into v_position;

    return v_position;
end;
$$;
create or replace function public.speichere_prepared_contract_signatur(
    p_kommunikationsvorgang_id bigint,
    p_signatur_revision integer,
    p_signatur_schluessel text,
    p_mitglied_id bigint,
    p_unterzeichner_name_snapshot text,
    p_vereinsfunktion_besetzung_id bigint,
    p_vertretung_id bigint,
    p_vertretene_besetzung_id bigint,
    p_storage_path text,
    p_signatur_sha256 text,
    p_unterzeichnet_am timestamptz default now()
)
returns public.prepared_contract_signatur
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_position public.prepared_contract_signatur%rowtype;
    v_signer record;
    v_name text;
    v_other_board_member bigint;
    v_other_represented_besetzung bigint;
begin
    if not public.is_admin_or_vorstand() or auth.uid() is null then
        raise exception 'Nur angemeldete administrative Vertragsbearbeitung darf Signaturen speichern.' using errcode = '42501';
    end if;

    select * into v_position from public.prepared_contract_signatur
    where kommunikationsvorgang_id = p_kommunikationsvorgang_id
      and signatur_revision = p_signatur_revision
      and signatur_schluessel = p_signatur_schluessel
    for update;
    if not found then
        raise exception 'Die Signaturposition wurde nicht vorbereitet.' using errcode = 'P0002';
    end if;
    if v_position.status <> 'offen' then
        raise exception 'Die Signaturposition wurde bereits unterschrieben.' using errcode = '55000';
    end if;
    if p_storage_path !~ ('^' || p_kommunikationsvorgang_id::text || '/' || p_signatur_revision::text || '/[^/]+/[0-9a-fA-F-]{36}[.]png$')
       or p_signatur_sha256 !~ '^[0-9a-f]{64}$' then
        raise exception 'Storage-Pfad oder Signatur-Hash ist ungültig.' using errcode = '23514';
    end if;
    if not exists (
        select 1 from storage.objects
        where bucket_id = 'prepared-contract-signatures' and name = p_storage_path
    ) then
        raise exception 'Das referenzierte Signaturbild liegt nicht im privaten Storage.' using errcode = '23514';
    end if;

    if v_position.unterzeichner_typ = 'vereinsunterzeichner' then
        select * into v_signer
        from public.vereinsfunktion_vertragsunterzeichner(p_unterzeichnet_am::date) s
        where s.mitglied_id = p_mitglied_id
          and s.vereinsfunktion_besetzung_id = p_vereinsfunktion_besetzung_id
          and s.vertretung_id is not distinct from p_vertretung_id
          and s.vertretene_besetzung_id is not distinct from p_vertretene_besetzung_id;
        if not found then
            raise exception 'Die Person ist zum Signaturzeitpunkt nicht zur Vertragsunterzeichnung berechtigt.' using errcode = '42501';
        end if;

        if v_position.signatur_schluessel in ('vorstand_1', 'vorstand_2') then
            select mitglied_id into v_other_board_member
            from public.prepared_contract_signatur
            where kommunikationsvorgang_id = p_kommunikationsvorgang_id
              and signatur_revision = p_signatur_revision
              and signatur_schluessel in ('vorstand_1', 'vorstand_2')
              and signatur_schluessel <> p_signatur_schluessel
              and status = 'unterschrieben';
            if v_other_board_member = p_mitglied_id then
                raise exception 'Vorstand 1 und Vorstand 2 müssen unterschiedliche natürliche Personen sein.' using errcode = '23514';
            end if;

            if p_vertretung_id is not null then
                select vertretene_besetzung_id into v_other_represented_besetzung
                from public.prepared_contract_signatur
                where kommunikationsvorgang_id = p_kommunikationsvorgang_id
                  and signatur_revision = p_signatur_revision
                  and signatur_schluessel in ('vorstand_1', 'vorstand_2')
                  and signatur_schluessel <> p_signatur_schluessel
                  and status = 'unterschrieben'
                  and vertretung_id is not null;
                if v_other_represented_besetzung = p_vertretene_besetzung_id then
                    raise exception 'Dieselbe vertretene Zeichnungsposition darf nicht beide Vorstandssignaturen abdecken.' using errcode = '23514';
                end if;
            end if;
        end if;

        update public.prepared_contract_signatur
        set status = 'unterschrieben',
            mitglied_id = v_signer.mitglied_id,
            unterzeichner_name_snapshot = v_signer.unterzeichner_name,
            vereinsfunktion_id = v_signer.vereinsfunktion_id,
            vereinsfunktion_bezeichnung_snapshot = v_signer.vereinsfunktion_bezeichnung,
            vereinsfunktion_besetzung_id = v_signer.vereinsfunktion_besetzung_id,
            vertretung_id = v_signer.vertretung_id,
            vertretene_vereinsfunktion_id = v_signer.vertretene_vereinsfunktion_id,
            vertretene_funktion_bezeichnung_snapshot = v_signer.vertretene_funktion_bezeichnung,
            vertretene_besetzung_id = v_signer.vertretene_besetzung_id,
            storage_bucket = 'prepared-contract-signatures',
            storage_path = p_storage_path,
            signatur_sha256 = p_signatur_sha256,
            unterzeichnet_am = p_unterzeichnet_am,
            unterzeichnet_von_auth_user_id = auth.uid()
        where id = v_position.id
        returning * into v_position;
    else
        select nullif(btrim(concat_ws(' ', vorname, name)), '') into v_name
        from public.mitglied where id = p_mitglied_id;
        v_name := coalesce(v_name, nullif(btrim(p_unterzeichner_name_snapshot), ''));
        if v_name is null then
            raise exception 'Für die private Unterschrift fehlt ein nachvollziehbarer Personen-Snapshot.' using errcode = '23514';
        end if;

        update public.prepared_contract_signatur
        set status = 'unterschrieben',
            mitglied_id = p_mitglied_id,
            unterzeichner_name_snapshot = v_name,
            storage_bucket = 'prepared-contract-signatures',
            storage_path = p_storage_path,
            signatur_sha256 = p_signatur_sha256,
            unterzeichnet_am = p_unterzeichnet_am,
            unterzeichnet_von_auth_user_id = auth.uid()
        where id = v_position.id
        returning * into v_position;
    end if;

    return v_position;
end;
$$;
create or replace function public.prepared_contract_signaturen_vollstaendig(
    p_kommunikationsvorgang_id bigint,
    p_signatur_revision integer
)
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_vorgang public.kommunikationsvorgang%rowtype;
begin
    if not public.is_admin_or_vorstand() and auth.role() is distinct from 'service_role' then
        raise exception 'Keine Berechtigung zur Prüfung von Vertragsunterschriften.' using errcode = '42501';
    end if;
    select * into v_vorgang from public.kommunikationsvorgang where id = p_kommunikationsvorgang_id;
    if not found or v_vorgang.vorgangstyp <> 'vertrag_signatur'
       or v_vorgang.signatur_revision is distinct from p_signatur_revision then
        return false;
    end if;
    return exists (
            select 1 from public.prepared_contract_signatur p
            where p.kommunikationsvorgang_id = p_kommunikationsvorgang_id
              and p.signatur_revision = p_signatur_revision
              and p.pflicht
        ) and not exists (
            select 1 from public.prepared_contract_signatur p
            where p.kommunikationsvorgang_id = p_kommunikationsvorgang_id
              and p.signatur_revision = p_signatur_revision
              and p.pflicht and p.status <> 'unterschrieben'
        );
end;
$$;
