-- KGV Hauptzähler – Basismodell
-- Stand: 2026-11-02
--
-- Zweck:
-- 1. Hauptzähler in public.zaehler zulassen, obwohl sie keiner Parzelle zugeordnet sind.
-- 2. Hauptzähler nach Nord/Süd unterscheiden.
-- 3. Dauerhafte RFID-Zuordnung an logische Hauptmessstellen binden,
--    damit ein Zählerwechsel keinen RFID-Wechsel erfordert.
--
-- Bestehende Parzellenzähler bleiben unverändert gültig.

begin;

-- ---------------------------------------------------------------------------
-- 1. public.zaehler erweitern
-- ---------------------------------------------------------------------------

alter table public.zaehler
    add column if not exists ist_hauptzaehler boolean not null default false;

alter table public.zaehler
    add column if not exists anlagenbereich text null;

-- Hauptzähler besitzen keine parzelle_id.
-- Normale Zähler behalten weiterhin zwingend eine parzelle_id.
alter table public.zaehler
    alter column parzelle_id drop not null;

-- Vorhandenen Constraint bei erneutem Lauf sauber ersetzen.
alter table public.zaehler
    drop constraint if exists zaehler_hauptzaehler_parzelle_bereich_chk;

alter table public.zaehler
    add constraint zaehler_hauptzaehler_parzelle_bereich_chk
    check (
        (
            ist_hauptzaehler = false
            and parzelle_id is not null
            and anlagenbereich is null
        )
        or
        (
            ist_hauptzaehler = true
            and parzelle_id is null
            and anlagenbereich in ('nord', 'sued')
        )
    );

comment on column public.zaehler.ist_hauptzaehler is
    'Kennzeichnet die vier Hauptzähler der Gesamtanlage.';

comment on column public.zaehler.anlagenbereich is
    'Nur bei Hauptzählern belegt: nord oder sued. Bei Parzellenzählern NULL.';


-- ---------------------------------------------------------------------------
-- 2. Dauerhafte Hauptmessstellen für RFID
-- ---------------------------------------------------------------------------

create table if not exists public.hauptzaehler_messstelle (
    id bigint generated by default as identity primary key,
    medium text not null,
    anlagenbereich text not null,
    rfid_tag_uid text null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),

    constraint hauptzaehler_messstelle_medium_chk
        check (medium in ('strom', 'wasser')),

    constraint hauptzaehler_messstelle_bereich_chk
        check (anlagenbereich in ('nord', 'sued')),

    constraint hauptzaehler_messstelle_medium_bereich_uq
        unique (medium, anlagenbereich),

    constraint hauptzaehler_messstelle_rfid_uq
        unique (rfid_tag_uid)
);

comment on table public.hauptzaehler_messstelle is
    'Vier dauerhafte logische Hauptmessstellen. RFID bleibt an der Messstelle und nicht am physischen Zähler.';

comment on column public.hauptzaehler_messstelle.medium is
    'strom oder wasser';

comment on column public.hauptzaehler_messstelle.anlagenbereich is
    'nord oder sued';

comment on column public.hauptzaehler_messstelle.rfid_tag_uid is
    'Dauerhafter RFID-Tag der Messstelle; bleibt bei Zählerwechsel unverändert.';


-- Vier logische Messstellen anlegen.
-- RFID bleibt zunächst NULL und kann später über die App zugeordnet werden.
insert into public.hauptzaehler_messstelle (medium, anlagenbereich)
values
    ('strom',  'nord'),
    ('strom',  'sued'),
    ('wasser', 'nord'),
    ('wasser', 'sued')
on conflict (medium, anlagenbereich) do nothing;

commit;
