-- P11 AP-03.2 / R04: membership termination is an audited, formal operation.
-- A generic authenticated PATCH must never be able to create or remove a
-- membership end date. Historical contract registrations remain protected by
-- their already SECURITY DEFINER operations and are deliberately not changed.

create table if not exists public.mitgliedschaftsbeendigung_audit (
  id bigint generated by default as identity primary key,
  mitglied_id bigint not null references public.mitglied(id),
  beendigt_am date not null,
  begruendung text not null check (length(btrim(begruendung)) > 0),
  sekundarentscheidung text null check (sekundarentscheidung in ('end_secondary', 'promote_secondary')),
  akteur_user_id uuid not null,
  erfasst_am timestamptz not null default now()
);

alter table public.mitgliedschaftsbeendigung_audit enable row level security;
revoke all on table public.mitgliedschaftsbeendigung_audit from public, anon, authenticated;

create or replace function public.guard_formal_membership_end()
returns trigger
language plpgsql
set search_path to 'public', 'pg_temp'
as $$
begin
  if old.mitglied_ende is distinct from new.mitglied_ende
     and current_setting('kgv.formal_membership_termination', true) is distinct from '1' then
    raise exception 'Das Mitgliedschaftsende darf nur über den formellen Beendigungsprozess gesetzt werden.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_guard_formal_membership_end on public.mitglied;
create trigger trg_guard_formal_membership_end
before update of mitglied_ende on public.mitglied
for each row execute function public.guard_formal_membership_end();

drop function public.end_membership(bigint, text);
create function public.end_membership(
  p_main_member_id bigint,
  p_secondary_decision text default null,
  p_begruendung text default null
)
returns table (
  success boolean,
  message text,
  updated_main_member jsonb,
  updated_secondary_member jsonb,
  secondary_decision text
)
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_user_id uuid := auth.uid();
  v_main_member public.mitglied%rowtype;
  v_secondary_member public.mitglied%rowtype;
  v_has_secondary boolean := false;
  v_end_date date := (public.kgv_local_now())::date;
  v_now_utc timestamp without time zone := now() at time zone 'UTC';
  v_begruendung text := nullif(btrim(p_begruendung), '');
  v_message text;
begin
  if v_user_id is null then
    raise exception 'Anmeldung erforderlich.' using errcode = '42501';
  end if;
  if not public.has_effective_permission(4) then
    raise exception 'Keine Berechtigung zum Beenden von Mitgliedschaften.' using errcode = '42501';
  end if;
  if v_begruendung is null then
    raise exception 'Für die formelle Beendigung ist eine Begründung erforderlich.' using errcode = '22023';
  end if;

  select m.* into v_main_member from public.mitglied m where m.id = p_main_member_id for update;
  if not found then raise exception 'Hauptmitglied wurde nicht gefunden.'; end if;
  if v_main_member.hauptmitglied_id is not null then raise exception 'Der Folgeentscheid ist nur für Hauptmitglieder verfügbar.'; end if;
  if v_main_member.mitglied_ende is not null then raise exception 'Die Mitgliedschaft ist bereits beendet.' using errcode = '23505'; end if;
  if v_main_member.lockedbyuserid is distinct from v_user_id or v_main_member.lockat is null or v_main_member.lockat <= v_now_utc - interval '10 minutes' then
    raise exception 'Kein gültiger Lock auf dem Hauptmitglied.' using errcode = '55P03';
  end if;
  if exists (
    select 1 from public.pachtverhaeltnis_beteiligung pb
    join public.pachtverhaeltnis pv on pv.id = pb.pachtverhaeltnis_id
    where pb.mitglied_id = v_main_member.id
      and pv.beendet_am is null
      and (pb.gueltig_bis is null or pb.gueltig_bis >= v_end_date)
  ) then
    raise exception 'Mitgliedschaft kann bei wirksamer Pachtbeteiligung nicht beendet werden.' using errcode = '23514';
  end if;

  select m.* into v_secondary_member from public.mitglied m where m.hauptmitglied_id = p_main_member_id order by m.id limit 1 for update;
  v_has_secondary := found;
  if not v_has_secondary and p_secondary_decision is not null then
    raise exception 'Ohne Nebenmitglied ist keine Folgeentscheidung zulässig.' using errcode = '22023';
  end if;
  if v_has_secondary and (p_secondary_decision is null or p_secondary_decision not in ('end_secondary', 'promote_secondary')) then
    raise exception 'Für das vorhandene Nebenmitglied ist eine gültige Folgeentscheidung erforderlich.' using errcode = '22023';
  end if;
  if v_has_secondary and v_secondary_member.lockedbyuserid is not null and v_secondary_member.lockedbyuserid <> v_user_id
     and (v_secondary_member.lockat is null or v_secondary_member.lockat + interval '10 minutes' > v_now_utc) then
    raise exception 'Das Nebenmitglied ist aktuell gesperrt.' using errcode = '55P03';
  end if;

  perform set_config('kgv.formal_membership_termination', '1', true);
  if v_has_secondary then
    if p_secondary_decision = 'end_secondary' then
      update public.mitglied set mitglied_ende = v_end_date, aktiv = false where id = v_secondary_member.id returning * into v_secondary_member;
      insert into public.mitgliedschaftsbeendigung_audit(mitglied_id, beendigt_am, begruendung, sekundarentscheidung, akteur_user_id)
      values (v_secondary_member.id, v_end_date, v_begruendung, 'end_secondary', v_user_id);
      v_message := 'Haupt- und Nebenmitglied wurden beendet.';
    else
      update public.mitglied set hauptmitglied_id = null, mitglied_ende = null, aktiv = true where id = v_secondary_member.id returning * into v_secondary_member;
      v_message := 'Hauptmitglied wurde beendet und das Nebenmitglied zum Hauptmitglied gemacht.';
    end if;
  else
    v_message := 'Mitgliedschaft wurde beendet.';
  end if;
  update public.mitglied set mitglied_ende = v_end_date, aktiv = false where id = v_main_member.id returning * into v_main_member;
  insert into public.mitgliedschaftsbeendigung_audit(mitglied_id, beendigt_am, begruendung, sekundarentscheidung, akteur_user_id)
  values (v_main_member.id, v_end_date, v_begruendung, p_secondary_decision, v_user_id);
  return query select true, v_message, to_jsonb(v_main_member), case when v_has_secondary then to_jsonb(v_secondary_member) else null::jsonb end, p_secondary_decision;
end;
$$;

revoke all on function public.end_membership(bigint, text, text) from public, anon;
grant execute on function public.end_membership(bigint, text, text) to authenticated;
comment on function public.end_membership(bigint, text, text) is
  'P11 AP-03.2: formal membership termination requires effective CanEditAllMembers, a lock, no current lease participation, and an audit reason.';
