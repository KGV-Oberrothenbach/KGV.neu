-- CX-04: a manually captured legal representative must sign before the board
-- decision, while their member row is deliberately created only on acceptance.
-- Preserve person-bound signing everywhere else.  The sole exception requires
-- the frozen legal-representative slot, its exact name snapshot and current
-- contract-administration permission.
create table if not exists public.mitglied_gesetzlicher_vertreter (
  id bigint generated by default as identity primary key,
  minderjaehriges_mitglied_id bigint not null references public.mitglied(id) on delete restrict,
  vertreter_mitglied_id bigint not null references public.mitglied(id) on delete restrict,
  gueltig_ab date not null,
  gueltig_bis date null,
  bemerkung text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ck_mgv_unterschiedliche_personen check (minderjaehriges_mitglied_id <> vertreter_mitglied_id),
  constraint ck_mgv_zeitraum check (gueltig_bis is null or gueltig_bis >= gueltig_ab)
);

create index if not exists ix_mgv_minderjaehrig_zeitraum
  on public.mitglied_gesetzlicher_vertreter(minderjaehriges_mitglied_id, gueltig_ab, gueltig_bis);
create index if not exists ix_mgv_vertreter
  on public.mitglied_gesetzlicher_vertreter(vertreter_mitglied_id);
create unique index if not exists ux_mgv_eine_offene_vertretung
  on public.mitglied_gesetzlicher_vertreter(minderjaehriges_mitglied_id)
  where gueltig_bis is null;

create or replace function public.guard_mitglied_gesetzlicher_vertreter_zeitraum()
returns trigger language plpgsql set search_path=public,pg_temp as $$
begin
  if exists (
    select 1 from public.mitglied_gesetzlicher_vertreter x
    where x.minderjaehriges_mitglied_id = new.minderjaehriges_mitglied_id
      and x.id is distinct from new.id
      and daterange(x.gueltig_ab, coalesce(x.gueltig_bis, 'infinity'::date), '[]')
          && daterange(new.gueltig_ab, coalesce(new.gueltig_bis, 'infinity'::date), '[]')
  ) then
    raise exception 'Mehrere gleichzeitig gültige gesetzliche Vertreter sind nicht zulässig' using errcode='23514';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_mgv_zeitraum on public.mitglied_gesetzlicher_vertreter;
create trigger trg_mgv_zeitraum before insert or update
  on public.mitglied_gesetzlicher_vertreter for each row
  execute function public.guard_mitglied_gesetzlicher_vertreter_zeitraum();

alter table public.mitglied_gesetzlicher_vertreter enable row level security;
