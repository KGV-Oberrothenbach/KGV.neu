-- Central, private storage for versioned PDF templates.  This is deliberately
-- independent of public.dokument and its Google-Drive lifecycle.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('pdf-templates', 'pdf-templates', false, 20971520, array['application/pdf', 'application/json'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.pdf_template_catalog (
    id bigint generated by default as identity primary key,
    template_key text not null check (template_key ~ '^[a-z0-9_-]+$'),
    version text not null check (version ~ '^v[0-9]+$'),
    storage_bucket text not null default 'pdf-templates' check (storage_bucket = 'pdf-templates'),
    storage_path text not null unique check (storage_path like 'templates/%'),
    content_type text not null check (content_type = 'application/pdf'),
    checksum text not null check (checksum ~ '^[0-9a-f]{64}$'),
    field_spec_path text not null unique check (field_spec_path like 'templates/%' and field_spec_path <> storage_path),
    field_spec_checksum text not null check (field_spec_checksum ~ '^[0-9a-f]{64}$'),
    field_spec_version text not null,
    renderer_version text not null,
    status text not null default 'draft' check (status in ('draft', 'published', 'retired')),
    aktiv boolean not null default false,
    created_at timestamptz not null default now(),
    published_at timestamptz,
    created_by uuid references auth.users(id),
    constraint uq_pdf_template_catalog_key_version unique (template_key, version),
    constraint ck_pdf_template_catalog_active_published check ((not aktiv) or status = 'published')
);

create unique index if not exists ux_pdf_template_catalog_one_active_per_key
    on public.pdf_template_catalog (template_key) where aktiv and status = 'published';

create or replace function public.protect_published_pdf_template()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
    if old.status = 'published' then
        if new.template_key <> old.template_key or new.version <> old.version or new.storage_bucket <> old.storage_bucket
           or new.storage_path <> old.storage_path or new.content_type <> old.content_type or new.checksum <> old.checksum
           or new.field_spec_path <> old.field_spec_path or new.field_spec_checksum <> old.field_spec_checksum
           or new.field_spec_version <> old.field_spec_version or new.renderer_version <> old.renderer_version
           or new.status <> old.status then
            raise exception 'Published PDF template versions are immutable' using errcode = '55000';
        end if;
    end if;
    if new.status = 'published' and old.status <> 'published' and new.published_at is null then new.published_at := now(); end if;
    return new;
end;
$$;

drop trigger if exists trg_protect_published_pdf_template on public.pdf_template_catalog;
create trigger trg_protect_published_pdf_template before update on public.pdf_template_catalog
for each row execute function public.protect_published_pdf_template();

create or replace function public.prevent_delete_published_pdf_template()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
    if old.status = 'published' then raise exception 'Published PDF template versions cannot be deleted' using errcode = '55000'; end if;
    return old;
end;
$$;
drop trigger if exists trg_prevent_delete_published_pdf_template on public.pdf_template_catalog;
create trigger trg_prevent_delete_published_pdf_template before delete on public.pdf_template_catalog
for each row execute function public.prevent_delete_published_pdf_template();

