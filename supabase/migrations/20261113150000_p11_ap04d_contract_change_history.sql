-- AP-04.4: Laufende Vertragsmerkmale sind nicht über den allgemeinen
-- Parzellen-Stammdatenpfad veränderbar. Die Wirksamkeit wird an eine bereits
-- finalisierte Vertragsfassung desselben laufenden Verhältnisses gebunden.
create table public.pacht_daten_audit (
 id bigint generated by default as identity primary key,
 pachtverhaeltnis_id bigint not null references public.pachtverhaeltnis(id),
 parzelle_id bigint not null references public.parzelle(id),
 pachtvertragsfassung_id bigint references public.pachtvertragsfassung(id),
 art text not null check(art in ('vertragsaenderung','historische_korrektur')),
 vorher jsonb not null, nachher jsonb not null,
 begruendung text not null, akteur_user_id uuid not null, erfasst_am timestamptz not null default now()
);
alter table public.pacht_daten_audit enable row level security;
revoke all on public.pacht_daten_audit from public, anon, authenticated;

create or replace function public.guard_pacht_parzellenmerkmale()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if (old.flaeche_qm is distinct from new.flaeche_qm or old.hat_strom is distinct from new.hat_strom or old.hat_wasser is distinct from new.hat_wasser)
    and exists(select 1 from public.pachtverhaeltnis p where p.parzelle_id=old.id and p.beendet_am is null)
    and current_setting('app.p11_signed_contract_change',true) is distinct from 'on' then
   raise exception 'Fläche und Anschlüsse einer laufend verpachteten Parzelle erfordern eine vollständig abgeschlossene Vertragsänderung.' using errcode='42501';
 end if;
 return new;
end $$;
drop trigger if exists trg_guard_pacht_parzellenmerkmale on public.parzelle;
create trigger trg_guard_pacht_parzellenmerkmale before update of flaeche_qm,hat_strom,hat_wasser on public.parzelle for each row execute function public.guard_pacht_parzellenmerkmale();

create or replace function public.guard_abgeschlossene_pachtdaten()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if current_setting('app.p11_historical_correction',true) is distinct from 'on'
    and ((tg_table_name='pachtverhaeltnis' and old.beendet_am is not null)
      or (tg_table_name='pachtverhaeltnis_beteiligung' and old.gueltig_bis is not null)) then
   raise exception 'Abgeschlossene Pachtdaten dürfen nur über eine auditierte Korrektur ergänzt werden.' using errcode='42501';
 end if;
 return new;
end $$;
drop trigger if exists trg_guard_abgeschlossenes_pachtverhaeltnis on public.pachtverhaeltnis;
create trigger trg_guard_abgeschlossenes_pachtverhaeltnis before update on public.pachtverhaeltnis for each row execute function public.guard_abgeschlossene_pachtdaten();
drop trigger if exists trg_guard_abgeschlossene_pachtbeteiligung on public.pachtverhaeltnis_beteiligung;
create trigger trg_guard_abgeschlossene_pachtbeteiligung before update on public.pachtverhaeltnis_beteiligung for each row execute function public.guard_abgeschlossene_pachtdaten();

create or replace function public.wende_signierte_parzellen_vertragsaenderung_an(p_pachtverhaeltnis_id bigint,p_pachtvertragsfassung_id bigint,p_flaeche_qm numeric,p_hat_strom boolean,p_hat_wasser boolean,p_begruendung text)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare v_pacht public.pachtverhaeltnis%rowtype; v_alt jsonb; v_neu jsonb; v_reason text:=nullif(btrim(p_begruendung),''); v_user uuid:=auth.uid();
begin
 if v_user is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für Vertragsänderungen.' using errcode='42501'; end if;
 if v_reason is null then raise exception 'Begründung erforderlich.' using errcode='22023'; end if;
 select * into v_pacht from public.pachtverhaeltnis where id=p_pachtverhaeltnis_id and beendet_am is null for update;
 if not found or not exists(select 1 from public.pachtvertragsfassung f join public.dokument d on d.id=f.dokument_id join public.kommunikationsvorgang k on k.final_dokument_id=d.id where f.id=p_pachtvertragsfassung_id and f.pachtverhaeltnis_id=v_pacht.id and k.status='erledigt') then raise exception 'Vollständig abgeschlossene Vertragsänderung fehlt oder passt nicht zum laufenden Pachtverhältnis.' using errcode='23514'; end if;
 select jsonb_build_object('flaeche_qm',flaeche_qm,'hat_strom',hat_strom,'hat_wasser',hat_wasser) into v_alt from public.parzelle where id=v_pacht.parzelle_id for update;
 perform set_config('app.p11_signed_contract_change','on',true);
 update public.parzelle set flaeche_qm=p_flaeche_qm,hat_strom=p_hat_strom,hat_wasser=p_hat_wasser where id=v_pacht.parzelle_id;
 select jsonb_build_object('flaeche_qm',flaeche_qm,'hat_strom',hat_strom,'hat_wasser',hat_wasser) into v_neu from public.parzelle where id=v_pacht.parzelle_id;
 insert into public.pacht_daten_audit(pachtverhaeltnis_id,parzelle_id,pachtvertragsfassung_id,art,vorher,nachher,begruendung,akteur_user_id) values(v_pacht.id,v_pacht.parzelle_id,p_pachtvertragsfassung_id,'vertragsaenderung',v_alt,v_neu,v_reason,v_user);
 return true;
end $$;
revoke all on function public.wende_signierte_parzellen_vertragsaenderung_an(bigint,bigint,numeric,boolean,boolean,text) from public,anon;
grant execute on function public.wende_signierte_parzellen_vertragsaenderung_an(bigint,bigint,numeric,boolean,boolean,text) to authenticated;
