-- K1: zentrale Grundlage für Dokument- und Kommunikationsvorgänge.
-- Kein verein_id: Jede Vereinsdatenbank ist weiterhin ein Einvereins-Schema.

create table public.kommunikationsvorgang (
  id bigint generated by default as identity primary key,
  vorgangstyp text not null check (vorgangstyp in ('vertrag_signatur', 'mail', 'druck')),
  dokumenttyp text not null check (length(btrim(dokumenttyp)) > 0),
  status text not null default 'entwurf' check (status in (
    'entwurf', 'vorbereitet', 'zur_signatur', 'mail_bereit', 'wird_versendet',
    'druck_bereit', 'erledigt', 'fehler', 'abgebrochen'
  )),
  mitglied_id bigint references public.mitglied(id) on delete restrict,
  parzelle_id bigint references public.parzelle(id) on delete restrict,
  entwurf_daten jsonb not null default '{}'::jsonb,
  revision integer not null default 1 check (revision >= 1),
  signatur_revision integer,
  signatur_gestartet_am timestamptz,
  vorschau_storage_bucket text,
  vorschau_storage_path text,
  final_storage_bucket text,
  final_storage_path text,
  empfaenger_email text,
  betreff text,
  mailtext text,
  versendet_am timestamptz,
  versendet_von uuid,
  fehlertext text,
  gedruckt_am timestamptz,
  gedruckt_von uuid,
  archiviert_am timestamptz,
  archiviert_von uuid,
  zugewiesen_an uuid,
  erstellt_am timestamptz not null default now(),
  erstellt_von uuid default auth.uid(),
  bearbeitet_am timestamptz not null default now(),
  bearbeitet_von uuid default auth.uid(),
  constraint kommunikationsvorgang_signatur_start_chk check (
    (signatur_revision is null and signatur_gestartet_am is null)
    or (signatur_revision = revision and signatur_gestartet_am is not null)
  )
);

comment on table public.kommunikationsvorgang is
  'Zentraler Vorgang für Vertragsentwürfe, Signaturen, Mailausgang, Druck und weitere Dokumenttypen.';
comment on column public.kommunikationsvorgang.entwurf_daten is
  'Strukturierte, fachliche Entwurfsdaten; nach Signaturbeginn der konkreten Revision unveränderlich.';

create index ix_kommunikationsvorgang_status on public.kommunikationsvorgang(status);
create index ix_kommunikationsvorgang_vorgangstyp on public.kommunikationsvorgang(vorgangstyp);
create index ix_kommunikationsvorgang_dokumenttyp on public.kommunikationsvorgang(dokumenttyp);
create index ix_kommunikationsvorgang_mitglied_id on public.kommunikationsvorgang(mitglied_id);
create index ix_kommunikationsvorgang_parzelle_id on public.kommunikationsvorgang(parzelle_id);
create index ix_kommunikationsvorgang_zugewiesen_an on public.kommunikationsvorgang(zugewiesen_an);
create index ix_kommunikationsvorgang_erstellt_am on public.kommunikationsvorgang(erstellt_am);
create index ix_kommunikationsvorgang_status_erstellt_am on public.kommunikationsvorgang(status, erstellt_am desc);

create or replace function public.guard_kommunikationsvorgang_update()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.erstellt_von := auth.uid();
      new.bearbeitet_von := auth.uid();
    end if;
    if new.signatur_gestartet_am is not null then
      new.signatur_gestartet_am := now();
      new.signatur_revision := new.revision;
    elsif new.signatur_revision is not null then
      raise exception 'signatur_revision requires signatur_gestartet_am' using errcode = '23514';
    end if;
    return new;
  end if;

  if old.signatur_gestartet_am is not null then
    if new.signatur_gestartet_am is distinct from old.signatur_gestartet_am
       or new.signatur_revision is distinct from old.signatur_revision
       or new.entwurf_daten is distinct from old.entwurf_daten
       or new.revision is distinct from old.revision
       or new.dokumenttyp is distinct from old.dokumenttyp
       or new.mitglied_id is distinct from old.mitglied_id
       or new.parzelle_id is distinct from old.parzelle_id then
      raise exception 'Signed communication workflow revision is immutable' using errcode = '55000';
    end if;
  elsif new.signatur_gestartet_am is not null then
    new.signatur_gestartet_am := now();
    new.signatur_revision := new.revision;
  elsif new.signatur_revision is not null then
    raise exception 'signatur_revision requires signatur_gestartet_am' using errcode = '23514';
  end if;

  if new.status is distinct from old.status
     and not (
       (old.status = 'entwurf' and new.status in ('vorbereitet', 'abgebrochen')) or
       (old.status = 'vorbereitet' and new.status in ('entwurf', 'zur_signatur', 'abgebrochen')) or
       (old.status = 'zur_signatur' and new.status in ('vorbereitet', 'mail_bereit', 'druck_bereit', 'erledigt', 'abgebrochen')) or
       (old.status = 'mail_bereit' and new.status in ('wird_versendet', 'abgebrochen')) or
       (old.status = 'wird_versendet' and new.status in ('erledigt', 'fehler')) or
       (old.status = 'druck_bereit' and new.status in ('erledigt', 'fehler', 'abgebrochen')) or
       (old.status = 'fehler' and new.status in ('mail_bereit', 'druck_bereit', 'abgebrochen'))
     ) then
    raise exception 'Invalid communication workflow status transition: % -> %', old.status, new.status using errcode = '23514';
  end if;

  if old.status = 'zur_signatur' and new.status = 'vorbereitet' and old.signatur_gestartet_am is not null then
    raise exception 'A started signature workflow cannot return to vorbereitet' using errcode = '55000';
  end if;

  new.bearbeitet_am := now();
  if auth.uid() is not null then
    new.bearbeitet_von := auth.uid();
  end if;
  return new;
end;
$$;

create trigger trg_kommunikationsvorgang_guard
before insert or update on public.kommunikationsvorgang
for each row execute function public.guard_kommunikationsvorgang_update();

alter table public.kommunikationsvorgang enable row level security;

create policy kommunikationsvorgang_admin_vorstand_all
on public.kommunikationsvorgang
for all to authenticated
using (
  exists (
    select 1 from public.current_app_user_context() c
    where c.role in ('admin', 'vorstand')
  )
)
with check (
  exists (
    select 1 from public.current_app_user_context() c
    where c.role in ('admin', 'vorstand')
  )
);

revoke all on table public.kommunikationsvorgang from public, anon;
grant select, insert, update, delete on table public.kommunikationsvorgang to authenticated;
revoke all on sequence public.kommunikationsvorgang_id_seq from public, anon;
grant usage, select on sequence public.kommunikationsvorgang_id_seq to authenticated;
grant all on table public.kommunikationsvorgang to service_role;
grant usage, select on sequence public.kommunikationsvorgang_id_seq to service_role;

revoke all on function public.guard_kommunikationsvorgang_update() from public;
grant execute on function public.guard_kommunikationsvorgang_update() to service_role;
