CREATE OR REPLACE FUNCTION public.validate_wartungsvertrag_dokument_workflow()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_assignment public.wartungsvertrag_zuordnungen%ROWTYPE;
    v_communication public.kommunikationsvorgang%ROWTYPE;
    v_document public.dokument%ROWTYPE;
BEGIN
    SELECT * INTO v_assignment
    FROM public.wartungsvertrag_zuordnungen
    WHERE id = NEW.wartungsvertrag_zuordnung_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Die Wartungsvertragszuordnung für den Dokumentvorgang wurde nicht gefunden.'
            USING ERRCODE = '23503';
    END IF;

    IF NEW.kommunikationsvorgang_id IS NOT NULL THEN
        SELECT * INTO v_communication
        FROM public.kommunikationsvorgang
        WHERE id = NEW.kommunikationsvorgang_id;
        IF NOT FOUND
           OR v_communication.vorgangstyp <> 'vertrag_signatur'
           OR v_communication.dokumenttyp <> 'wartungsvertrag'
           OR v_communication.wartungsvertrag_zuordnung_id IS DISTINCT FROM NEW.wartungsvertrag_zuordnung_id
           OR v_communication.mitglied_id IS DISTINCT FROM v_assignment.hauptmitglied_id THEN
            RAISE EXCEPTION 'Der Signaturvorgang passt nicht zur Wartungsvertragszuordnung und ihrem Hauptmitglied.'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF NEW.dokument_id IS NOT NULL THEN
        SELECT * INTO v_document
        FROM public.dokument
        WHERE id = NEW.dokument_id;
        IF NOT FOUND
           OR v_document.source_wartungsvertrag_zuordnung_id IS DISTINCT FROM NEW.wartungsvertrag_zuordnung_id
           OR v_document.mitglied_id IS DISTINCT FROM v_assignment.hauptmitglied_id THEN
            RAISE EXCEPTION 'Das Wartungsvertragsdokument passt nicht zur Zuordnung und ihrem Hauptmitglied.'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    NEW.bearbeitet_am := now();
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_validate_wartungsvertrag_dokument_workflow
    ON public.wartungsvertrag_dokument_workflow;
CREATE TRIGGER trg_validate_wartungsvertrag_dokument_workflow
    BEFORE INSERT OR UPDATE ON public.wartungsvertrag_dokument_workflow
    FOR EACH ROW EXECUTE FUNCTION public.validate_wartungsvertrag_dokument_workflow();
