       OR v_communication.wartungsvertrag_zuordnung_id IS DISTINCT FROM NEW.source_wartungsvertrag_zuordnung_id
       OR NEW.mitglied_id IS DISTINCT FROM v_assignment.hauptmitglied_id THEN
        RAISE EXCEPTION 'Das finale Wartungsvertragsdokument passt nicht zum Signaturvorgang und Hauptmitglied.'
            USING ERRCODE = '23514';
