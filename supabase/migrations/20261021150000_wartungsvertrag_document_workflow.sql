ALTER TABLE public.kommunikationsvorgang
    ADD COLUMN IF NOT EXISTS wartungsvertrag_zuordnung_id bigint;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.kommunikationsvorgang'::regclass
          AND conname = 'kommunikationsvorgang_wvz_fk'
    ) THEN
        ALTER TABLE public.kommunikationsvorgang
            ADD CONSTRAINT kommunikationsvorgang_wvz_fk
            FOREIGN KEY (wartungsvertrag_zuordnung_id)
            REFERENCES public.wartungsvertrag_zuordnungen(id) ON DELETE RESTRICT;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.kommunikationsvorgang'::regclass
          AND conname = 'kommunikationsvorgang_wvz_type_chk'
    ) THEN
        ALTER TABLE public.kommunikationsvorgang
            ADD CONSTRAINT kommunikationsvorgang_wvz_type_chk
            CHECK (
                wartungsvertrag_zuordnung_id IS NULL
                OR (vorgangstyp = 'vertrag_signatur' AND dokumenttyp = 'wartungsvertrag')
            );
    END IF;
END;
$$;
