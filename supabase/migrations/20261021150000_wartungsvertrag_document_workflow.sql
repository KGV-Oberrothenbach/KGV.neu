CREATE TABLE IF NOT EXISTS public.wartungsvertrag_dokument_workflow (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wartungsvertrag_zuordnung_id bigint NOT NULL
        REFERENCES public.wartungsvertrag_zuordnungen(id) ON DELETE RESTRICT,
    kommunikationsvorgang_id bigint
        REFERENCES public.kommunikationsvorgang(id) ON DELETE RESTRICT,
    dokument_id bigint
        REFERENCES public.dokument(id) ON DELETE RESTRICT,
    status text NOT NULL DEFAULT 'dokument_ausstehend'
        CHECK (status IN ('dokument_ausstehend', 'erzeugungsfehler', 'signatur_vorgang', 'abgeschlossen')),
    fehlermeldung text,
    versuche integer NOT NULL DEFAULT 0 CHECK (versuche >= 0),
    erstellt_am timestamptz NOT NULL DEFAULT now(),
    bearbeitet_am timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT wartungsvertrag_dokument_workflow_assignment_uq UNIQUE (wartungsvertrag_zuordnung_id),
    CONSTRAINT wartungsvertrag_dokument_workflow_communication_uq UNIQUE (kommunikationsvorgang_id),
    CONSTRAINT wartungsvertrag_dokument_workflow_document_uq UNIQUE (dokument_id)
);
ALTER TABLE public.wartungsvertrag_dokument_workflow ENABLE ROW LEVEL SECURITY;
