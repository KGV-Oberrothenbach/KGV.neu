-- `vertragsunterzeichnung` is deliberately not seeded: purposes are free data,
-- and no existing function receives a signing use implicitly.
create or replace function public.vereinsfunktion_besetzungen_fuer_verwendungszweck(
    p_verwendungszweck text,
    p_stichtag date default current_date
)
returns table (
    vereinsfunktion_id bigint,
    schluessel text,
    bezeichnung text,
    besetzung_id bigint,
    mitglied_id bigint,
    gueltig_ab date,
    gueltig_bis date,
    sort_order smallint
)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
    select f.id, f.schluessel, f.bezeichnung, b.id, b.mitglied_id,
           b.gueltig_ab, b.gueltig_bis, b.sort_order
      from public.vereinsfunktion f
      join public.vereinsfunktion_verwendung v
        on v.vereinsfunktion_id = f.id
      join public.vereinsfunktion_besetzung b
        on b.vereinsfunktion_id = f.id
     where f.aktiv
       and v.verwendungszweck = p_verwendungszweck
       and b.gueltig_ab <= p_stichtag
       and (b.gueltig_bis is null or b.gueltig_bis >= p_stichtag)
     order by v.sort_order, f.schluessel, b.sort_order, b.id;
$$;
revoke all on function public.vereinsfunktion_besetzungen_fuer_verwendungszweck(text, date) from public;
grant execute on function public.vereinsfunktion_besetzungen_fuer_verwendungszweck(text, date) to authenticated, service_role;
