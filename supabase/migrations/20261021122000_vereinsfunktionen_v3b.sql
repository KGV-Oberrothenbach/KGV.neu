-- V3b: configurable single occupancy, explicit temporary representation and
-- an RLS-respecting lookup for valid function assignments.

alter table public.vereinsfunktion
    add column if not exists erlaubt_mehrfachbesetzung boolean;
update public.vereinsfunktion
set erlaubt_mehrfachbesetzung = true
where erlaubt_mehrfachbesetzung is null;
alter table public.vereinsfunktion
    alter column erlaubt_mehrfachbesetzung set default true,
    alter column erlaubt_mehrfachbesetzung set not null;
comment on column public.vereinsfunktion.erlaubt_mehrfachbesetzung is
    'TRUE erlaubt zeitgleich mehrere Besetzungen; FALSE verlangt eine Einzelbesetzung ohne zeitliche Überschneidung.';
create or replace function public.validate_vereinsfunktion_besetzung_einzelbesetzung()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
    v_erlaubt_mehrfachbesetzung boolean;
begin
    -- The row lock serializes assignment writes with a change to single occupancy.
    select f.erlaubt_mehrfachbesetzung
      into v_erlaubt_mehrfachbesetzung
      from public.vereinsfunktion f
     where f.id = new.vereinsfunktion_id
       for update;

    if v_erlaubt_mehrfachbesetzung = false and exists (
        select 1
          from public.vereinsfunktion_besetzung b
         where b.vereinsfunktion_id = new.vereinsfunktion_id
           and b.id is distinct from new.id
           and daterange(b.gueltig_ab, coalesce(b.gueltig_bis, 'infinity'::date), '[]')
               && daterange(new.gueltig_ab, coalesce(new.gueltig_bis, 'infinity'::date), '[]')
    ) then
        raise exception 'Einzelbesetzung der Vereinsfunktion darf sich zeitlich nicht überschneiden'
            using errcode = '23514';
    end if;

    return new;
end;
$$;
create or replace function public.validate_vereinsfunktion_einzelbesetzung_umschaltung()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if new.erlaubt_mehrfachbesetzung = false
       and old.erlaubt_mehrfachbesetzung is distinct from new.erlaubt_mehrfachbesetzung
       and exists (
           select 1
             from public.vereinsfunktion_besetzung b1
             join public.vereinsfunktion_besetzung b2
               on b2.vereinsfunktion_id = b1.vereinsfunktion_id
              and b2.id > b1.id
              and daterange(b1.gueltig_ab, coalesce(b1.gueltig_bis, 'infinity'::date), '[]')
                  && daterange(b2.gueltig_ab, coalesce(b2.gueltig_bis, 'infinity'::date), '[]')
            where b1.vereinsfunktion_id = new.id
       ) then
        raise exception 'Vereinsfunktion kann wegen bestehender zeitlicher Überschneidungen nicht auf Einzelbesetzung umgestellt werden'
            using errcode = '23514';
    end if;

    return new;
end;
$$;
drop trigger if exists trg_vereinsfunktion_besetzung_einzelbesetzung on public.vereinsfunktion_besetzung;
create trigger trg_vereinsfunktion_besetzung_einzelbesetzung
before insert or update of vereinsfunktion_id, gueltig_ab, gueltig_bis
on public.vereinsfunktion_besetzung
for each row execute function public.validate_vereinsfunktion_besetzung_einzelbesetzung();
drop trigger if exists trg_vereinsfunktion_einzelbesetzung_umschaltung on public.vereinsfunktion;
create trigger trg_vereinsfunktion_einzelbesetzung_umschaltung
before update of erlaubt_mehrfachbesetzung
on public.vereinsfunktion
for each row execute function public.validate_vereinsfunktion_einzelbesetzung_umschaltung();
create table public.vereinsfunktion_vertretung (
    id bigint generated by default as identity primary key,
    vertretene_besetzung_id bigint not null references public.vereinsfunktion_besetzung(id) on delete restrict,
    vertreter_besetzung_id bigint not null references public.vereinsfunktion_besetzung(id) on delete restrict,
    gueltig_ab date not null,
    gueltig_bis date null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint ck_vereinsfunktion_vertretung_zeitraum check (gueltig_bis is null or gueltig_bis >= gueltig_ab),
    constraint ck_vereinsfunktion_vertretung_keine_selbstreferenz check (vertretene_besetzung_id <> vertreter_besetzung_id)
);
create index ix_vereinsfunktion_vertretung_vertretene_besetzung
    on public.vereinsfunktion_vertretung (vertretene_besetzung_id, gueltig_ab, gueltig_bis);
create index ix_vereinsfunktion_vertretung_vertreter_besetzung
    on public.vereinsfunktion_vertretung (vertreter_besetzung_id, gueltig_ab, gueltig_bis);
create or replace function public.set_updated_at_vereinsfunktion_vertretung()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;
create or replace function public.validate_vereinsfunktion_vertretung()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
    v_vertretene public.vereinsfunktion_besetzung%rowtype;
    v_vertreter public.vereinsfunktion_besetzung%rowtype;
begin
    select * into v_vertretene
      from public.vereinsfunktion_besetzung
     where id = new.vertretene_besetzung_id
       for update;
    select * into v_vertreter
      from public.vereinsfunktion_besetzung
     where id = new.vertreter_besetzung_id
       for update;

    if v_vertretene.mitglied_id = v_vertreter.mitglied_id then
        raise exception 'Eine Person kann nicht ihre eigene Besetzung vertreten'
            using errcode = '23514';
    end if;

    if not (
        daterange(new.gueltig_ab, coalesce(new.gueltig_bis, 'infinity'::date), '[]')
            <@ daterange(v_vertretene.gueltig_ab, coalesce(v_vertretene.gueltig_bis, 'infinity'::date), '[]')
        and daterange(new.gueltig_ab, coalesce(new.gueltig_bis, 'infinity'::date), '[]')
            <@ daterange(v_vertreter.gueltig_ab, coalesce(v_vertreter.gueltig_bis, 'infinity'::date), '[]')
    ) then
        raise exception 'Der Vertretungszeitraum muss innerhalb beider zugrunde liegenden Besetzungszeiträume liegen'
            using errcode = '23514';
    end if;

    return new;
end;
$$;
create or replace function public.validate_vereinsfunktion_besetzung_vertretungsgrenzen()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if new.vereinsfunktion_id is distinct from old.vereinsfunktion_id
       and exists (
           select 1
             from public.vereinsfunktion_vertretung v
            where v.vertretene_besetzung_id = new.id
               or v.vertreter_besetzung_id = new.id
       ) then
        raise exception 'Vereinsfunktion einer in einer Vertretung verwendeten Besetzung darf nicht geändert werden'
            using errcode = '23514';
    end if;

    if exists (
        select 1
          from public.vereinsfunktion_vertretung v
          join public.vereinsfunktion_besetzung andere_besetzung
            on andere_besetzung.id = case
                when v.vertretene_besetzung_id = new.id then v.vertreter_besetzung_id
                else v.vertretene_besetzung_id
            end
         where (v.vertretene_besetzung_id = new.id or v.vertreter_besetzung_id = new.id)
           and (
               new.mitglied_id = andere_besetzung.mitglied_id
               or not (
                   daterange(v.gueltig_ab, coalesce(v.gueltig_bis, 'infinity'::date), '[]')
                       <@ daterange(new.gueltig_ab, coalesce(new.gueltig_bis, 'infinity'::date), '[]')
                   and daterange(v.gueltig_ab, coalesce(v.gueltig_bis, 'infinity'::date), '[]')
                       <@ daterange(andere_besetzung.gueltig_ab, coalesce(andere_besetzung.gueltig_bis, 'infinity'::date), '[]')
               )
           )
    ) then
        raise exception 'Besetzung kann bestehende Vertretungen nicht ungültig machen'
            using errcode = '23514';
    end if;

    return new;
end;
$$;
