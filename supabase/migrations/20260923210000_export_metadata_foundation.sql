grant select on table public.app_export_definition,
  public.app_export_filter_definition,
  public.app_export_column_definition to authenticated;
grant all on table public.app_export_definition,
  public.app_export_filter_definition,
  public.app_export_column_definition to service_role;
grant usage, select on sequence public.app_export_filter_definition_id_seq,
  public.app_export_column_definition_id_seq to authenticated, service_role;
