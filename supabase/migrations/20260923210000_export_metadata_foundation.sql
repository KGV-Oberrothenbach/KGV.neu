-- Historical repair: the export metadata tables existed in the remote schema
-- before the first export migration, but their original migration was missing
-- from this repository. This file must stay before 20260923223000.

create table if not exists public.app_export_definition (
  export_key text primary key,
  titel text not null,
  beschreibung text,
  quelle_typ text not null check (quelle_typ in ('rpc', 'view')),
  quelle_name text not null,
  aktiv boolean not null default true,
  standard_sortierung text,
  standard_ausgabe text check (standard_ausgabe in ('anzeige', 'pdf', 'csv', 'excel')),
  erlaubt_anzeige boolean not null default true,
  erlaubt_pdf boolean not null default true,
  erlaubt_csv boolean not null default true,
  erlaubt_excel boolean not null default false,
  pdf_format text,
  pdf_orientation text,
  sortierung integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.app_export_filter_definition (
  id bigint generated by default as identity primary key,
  export_key text not null references public.app_export_definition(export_key) on delete cascade,
  filter_key text not null,
  label text not null,
  typ text not null check (typ in ('boolean', 'text', 'select')),
  pflicht boolean not null default false,
  standardwert text,
  optionen_json jsonb,
  sortierung integer not null default 0,
  aktiv boolean not null default true,
  unique (export_key, filter_key)
);

create table if not exists public.app_export_column_definition (
  id bigint generated by default as identity primary key,
  export_key text not null references public.app_export_definition(export_key) on delete cascade,
  column_key text not null,
  label_kurz text not null,
  label_lang text not null,
  sortierung integer not null default 0,
  standard_sichtbar boolean not null default true,
  einblendbar boolean not null default true,
  ist_sortierspalte boolean not null default false,
  unique (export_key, column_key)
);

drop trigger if exists trg_app_export_definition_updated_at on public.app_export_definition;
create trigger trg_app_export_definition_updated_at
before update on public.app_export_definition
for each row execute function public.set_updated_at();

alter table public.app_export_definition enable row level security;
alter table public.app_export_filter_definition enable row level security;
alter table public.app_export_column_definition enable row level security;

drop policy if exists app_export_definition_select_admin_vorstand on public.app_export_definition;
create policy app_export_definition_select_admin_vorstand
on public.app_export_definition for select to authenticated
using (exists (
  select 1 from public.app_user au
  where au.user_id = auth.uid()
    and lower(coalesce(au.role, '')) in ('admin', 'vorstand')
));

drop policy if exists app_export_filter_definition_select_admin_vorstand on public.app_export_filter_definition;
create policy app_export_filter_definition_select_admin_vorstand
on public.app_export_filter_definition for select to authenticated
using (exists (
  select 1 from public.app_user au
  where au.user_id = auth.uid()
    and lower(coalesce(au.role, '')) in ('admin', 'vorstand')
));

drop policy if exists app_export_column_definition_select_admin_vorstand on public.app_export_column_definition;
create policy app_export_column_definition_select_admin_vorstand
