-- DOC-DB1: Zentral verwaltete, zeitlich gültige Vereinsunterlagen.
-- Für eine Fassung wird kein "is_current" gepflegt. Die Gültigkeit ergibt sich
-- ausschließlich aus dem Zeitraum gueltig_ab bis gueltig_bis.

create extension if not exists btree_gist;
create table public.vereinsdokument_typ (
  code text primary key,
  bezeichnung text not null,
  pflicht boolean not null default true,
  constraint vereinsdokument_typ_code_chk check (code in (
    'satzung',
    'kleingartenordnung',
    'beitragsordnung',
    'arbeitsordnung'
  )),
  constraint vereinsdokument_typ_bezeichnung_chk check (length(btrim(bezeichnung)) > 0)
);
insert into public.vereinsdokument_typ (code, bezeichnung, pflicht)
values
  ('satzung', 'Satzung', true),
  ('kleingartenordnung', 'Kleingartenordnung', true),
  ('beitragsordnung', 'Beitragsordnung', true),
  ('arbeitsordnung', 'Arbeitsordnung', true)
on conflict (code) do update
set bezeichnung = excluded.bezeichnung,
    pflicht = excluded.pflicht;
create table public.vereinsdokument_fassung (
  id bigint generated by default as identity primary key,
  dokumenttyp_code text not null references public.vereinsdokument_typ(code) on delete restrict,
  fassung text not null,
  gueltig_ab date not null,
  gueltig_bis date,
  storage_path text,
  dateiname text,
  sha256 text,
  erstellt_am timestamptz not null default now(),
  erstellt_von uuid references auth.users(id) on delete set null,
  constraint vereinsdokument_fassung_typ_fassung_uq unique (dokumenttyp_code, fassung),
  constraint vereinsdokument_fassung_zeitraum_chk check (
    gueltig_bis is null or gueltig_bis >= gueltig_ab
  ),
  constraint vereinsdokument_fassung_fassung_chk check (length(btrim(fassung)) > 0),
  constraint vereinsdokument_fassung_datei_metadaten_chk check (
    (storage_path is null and dateiname is null and sha256 is null)
    or (
      length(btrim(storage_path)) > 0
      and length(btrim(dateiname)) > 0
      and sha256 ~ '^[0-9a-f]{64}$'
    )
  ),
  constraint vereinsdokument_fassung_zeitraum_ohne_ueberschneidung exclude using gist (
    dokumenttyp_code with =,
    daterange(gueltig_ab, gueltig_bis, '[]') with &&
  )
);
-- Eine noch nicht befristete Fassung je Typ. Bei einem Nachfolger wird die
-- bisherige Fassung fachlich beendet; dadurch bleiben historische Stichtage eindeutig.
create unique index ux_vereinsdokument_fassung_eine_offene_pro_typ
  on public.vereinsdokument_fassung (dokumenttyp_code)
  where gueltig_bis is null;
create or replace function public.guard_vereinsdokument_fassung_datei()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    if auth.uid() is not null then
      new.erstellt_von := auth.uid();
    end if;
    return new;
  end if;

  if new.dokumenttyp_code is distinct from old.dokumenttyp_code
     or new.fassung is distinct from old.fassung then
    raise exception 'Document type and version are immutable' using errcode = '55000';
  end if;

  if old.storage_path is not null
     and (
       new.storage_path is distinct from old.storage_path
       or new.dateiname is distinct from old.dateiname
       or new.sha256 is distinct from old.sha256
     ) then
    raise exception 'Stored club-document file metadata is immutable' using errcode = '55000';
  end if;

  return new;
end;
$$;
create trigger trg_vereinsdokument_fassung_datei_guard
before insert or update on public.vereinsdokument_fassung
for each row execute function public.guard_vereinsdokument_fassung_datei();
comment on table public.vereinsdokument_typ is
  'Abschließende fachliche Typen der zentral verwalteten Vereinsunterlagen.';
comment on table public.vereinsdokument_fassung is
  'Zeitlich gültige Fassungen von Vereinsunterlagen. Die aktuelle Fassung wird am Stichtag aus dem Gültigkeitszeitraum ermittelt.';
comment on column public.vereinsdokument_fassung.storage_path is
  'Unveränderlicher Pfad im privaten Bucket vereinsregelwerke; vorgesehenes Namensschema: vereinsunterlagen/<dokumenttyp>/<fassung>/<dateiname>.';
-- Bestehenden, bereits privaten Bucket weiterverwenden. Vereinsunterlagen
-- werden dort strikt getrennt von den bisherigen Regelwerkdateien abgelegt.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'vereinsregelwerke',
  'vereinsregelwerke',
  false,
  10485760,
  array['application/pdf']
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;
