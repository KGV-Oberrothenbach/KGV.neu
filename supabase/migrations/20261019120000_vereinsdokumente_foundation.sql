-- Die Dateien bleiben privat und nach Upload für Client-Rollen unveränderlich.
-- Spätere Server-Dienste lesen sie mit der Service-Rolle.
create policy vereinsunterlagen_read_admin_vorstand
on storage.objects
for select to authenticated
using (
  bucket_id = 'vereinsregelwerke'
  and (storage.foldername(name))[1] = 'vereinsunterlagen'
  and exists (
    select 1 from public.current_app_user_context() c
    where c.role in ('admin', 'vorstand')
  )
);
create policy vereinsunterlagen_insert_admin_vorstand
on storage.objects
for insert to authenticated
with check (
  bucket_id = 'vereinsregelwerke'
  and (storage.foldername(name))[1] = 'vereinsunterlagen'
  and exists (
    select 1 from public.current_app_user_context() c
    where c.role in ('admin', 'vorstand')
  )
);
