-- P11 AP-04.2 completion: aftercare may only finish once and protocol links
-- remain historical evidence. A successor is factual only when its legal
-- lease is active and has an active principal participant.
create table public.pacht_nachsorge_ereignis (
 id bigint generated by default as identity primary key,
 nachsorge_id bigint not null references public.pacht_nachsorge(id),
 art text not null check(art in ('ordentlich','entlassung','nachpaechteruebernahme','protokoll_zugeordnet')),
 begruendung text not null, akteur_user_id uuid not null, erfasst_am timestamptz not null default now(),
 protokoll_id bigint null references public.parzellen_protokoll(id),
 nachfolger_pachtverhaeltnis_id bigint null references public.pachtverhaeltnis(id)
);
alter table public.pacht_nachsorge_ereignis enable row level security;
revoke all on public.pacht_nachsorge_ereignis from public,anon,authenticated;

create or replace function public.beende_pacht_nachsorge(p_nachsorge_id bigint,p_art text,p_begruendung text,p_nachfolger_pachtverhaeltnis_id bigint default null)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare n public.pacht_nachsorge%rowtype; caller uuid:=auth.uid(); reason text:=nullif(btrim(p_begruendung),''); successor public.pachtverhaeltnis%rowtype;
begin
 if caller is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für Nachsorgeentscheidungen.' using errcode='42501'; end if;
 if p_art not in ('ordentlich','entlassung','nachpaechteruebernahme') or reason is null then raise exception 'Art und Begründung sind erforderlich.' using errcode='22023'; end if;
 select * into n from public.pacht_nachsorge where id=p_nachsorge_id for update;
 if not found then raise exception 'Nachsorge wurde nicht gefunden.' using errcode='P0002'; end if;
 if n.beendet_am is not null then return true; end if;
 if p_art='ordentlich' and public.kgv_local_now()::date<n.endet_am then raise exception 'Ordentliche Beendigung ist erst zum Nachsorgeende zulässig.' using errcode='23514'; end if;
 if p_art='nachpaechteruebernahme' then
   if p_nachfolger_pachtverhaeltnis_id is null then raise exception 'Nachfolgepachtverhältnis erforderlich.' using errcode='22023'; end if;
   select * into successor from public.pachtverhaeltnis where id=p_nachfolger_pachtverhaeltnis_id for key share;
   if not found or successor.parzelle_id<>n.parzelle_id or successor.beendet_am is not null or not exists(select 1 from public.pachtverhaeltnis_beteiligung b join public.mitglied m on m.id=b.mitglied_id where b.pachtverhaeltnis_id=successor.id and b.rolle='hauptpaechter' and b.gueltig_ab<=public.kgv_local_now()::date and (b.gueltig_bis is null or b.gueltig_bis>=public.kgv_local_now()::date) and m.aktiv and m.aufnahme_status='aufgenommen') then
     raise exception 'Es liegt keine tatsächliche Nachpächterübernahme vor.' using errcode='23514';
   end if;
 end if;
 update public.pacht_nachsorge set beendet_am=least(public.kgv_local_now()::date,endet_am),beendigungsgrund=p_art,beschlossen_von=caller,beschlossen_am=now() where id=n.id;
 insert into public.pacht_nachsorge_ereignis(nachsorge_id,art,begruendung,akteur_user_id,nachfolger_pachtverhaeltnis_id) values(n.id,p_art,reason,caller,p_nachfolger_pachtverhaeltnis_id);
 return true;
end $$;

create or replace function public.ordne_nachsorge_protokoll_zu(p_nachsorge_id bigint,p_protokoll_id bigint,p_begruendung text)
returns boolean language plpgsql security definer set search_path=public,pg_temp as $$
declare n public.pacht_nachsorge%rowtype; p public.parzellen_protokoll%rowtype; caller uuid:=auth.uid(); reason text:=nullif(btrim(p_begruendung),'');
begin
 if caller is null or not public.has_effective_permission(524288) then raise exception 'Keine Berechtigung für Übergabeprotokolle.' using errcode='42501'; end if;
 if reason is null then raise exception 'Begründung erforderlich.' using errcode='22023'; end if;
 select * into n from public.pacht_nachsorge where id=p_nachsorge_id for update; select * into p from public.parzellen_protokoll where id=p_protokoll_id for update;
 if not found or p.parzelle_id<>n.parzelle_id or p.protokoll_typ not in ('rueckgabe','uebernahme') or p.status<>'abgeschlossen' then raise exception 'Abgeschlossenes passendes Übergabeprotokoll erforderlich.' using errcode='23514'; end if;
 if p.pachtverhaeltnis_id is not null and p.pachtverhaeltnis_id<>n.pachtverhaeltnis_id then raise exception 'Protokoll gehört zu einem anderen Pachtverhältnis.' using errcode='23514'; end if;
 update public.parzellen_protokoll set pachtverhaeltnis_id=n.pachtverhaeltnis_id where id=p.id;
 insert into public.pacht_nachsorge_ereignis(nachsorge_id,art,begruendung,akteur_user_id,protokoll_id) values(n.id,'protokoll_zugeordnet',reason,caller,p.id);
 return true;
end $$;
revoke all on function public.beende_pacht_nachsorge(bigint,text,text,bigint),public.ordne_nachsorge_protokoll_zu(bigint,bigint,text) from public,anon;
grant execute on function public.beende_pacht_nachsorge(bigint,text,text,bigint),public.ordne_nachsorge_protokoll_zu(bigint,bigint,text) to authenticated;
