create or replace function public.trg_reserve_vertragsnummer()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_art text;
  v_demo boolean;
  v_quelle_art text;
  v_quelle_id bigint;
begin
  if new.status <> 'zur_signatur' or old.status is not distinct from 'zur_signatur' then
    return new;
  end if;

  v_art := case new.dokumenttyp
    when 'mitgliedsantrag' then 'mitgliedsantrag'
    when 'pachtvertrag' then 'pachtvertrag'
    when 'wartungsvertrag' then 'wartungsvertrag'
  end;
  if v_art is null then
    return new;
  end if;

  if v_art = 'wartungsvertrag' then
    if new.wartungsvertrag_id is null then
      raise exception 'Dem Wartungsvertrags-Signaturvorgang fehlt die fachliche Vertragszuordnung.'
        using errcode = '23514';
    end if;
    select is_demo into v_demo
    from public.wartungsvertraege
    where id = new.wartungsvertrag_id;
    if not found then
      raise exception 'Der Wartungsvertrag für die Nummernreservierung wurde nicht gefunden.'
        using errcode = '23503';
    end if;
    v_quelle_art := 'wartungsvertrag';
    v_quelle_id := new.wartungsvertrag_id;
  else
    select coalesce(is_demo, false) into v_demo
    from public.mitglied
    where id = new.mitglied_id;
    v_quelle_art := 'kommunikationsvorgang';
    v_quelle_id := new.id;
  end if;

  perform public.reserve_fachnummer(v_art, v_quelle_art, v_quelle_id, coalesce(v_demo, false));
  return new;
end;
$$;

create or replace function public.validate_wartungsvertrag_kommunikationsvorgang_link()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_assignment public.wartungsvertrag_zuordnungen%rowtype;
  v_change public.wartungsvertrag_grundlegende_aenderung%rowtype;
begin
  if new.wartungsvertrag_zuordnung_id is not null then
    select * into v_assignment
    from public.wartungsvertrag_zuordnungen
    where id = new.wartungsvertrag_zuordnung_id;
    if not found
       or new.mitglied_id is distinct from v_assignment.vertragspartei_mitglied_id
       or new.parzelle_id is not null then
      raise exception 'Der Wartungsvertragsvorgang passt nicht zur Zuordnung und ihrer Vertragspartei.'
        using errcode = '23514';
    end if;
    if new.wartungsvertrag_id is null then
      new.wartungsvertrag_id := v_assignment.wartungsvertrag_id;
    elsif new.wartungsvertrag_id is distinct from v_assignment.wartungsvertrag_id then
      raise exception 'Der Wartungsvertrags-Signaturvorgang verweist auf eine andere Vertragsdefinition.'
        using errcode = '23514';
    end if;
    if (new.vorgangstyp = 'vertrag_signatur' and new.dokumenttyp = 'wartungsvertrag')
       or (new.vorgangstyp = 'dokument_erzeugung' and new.dokumenttyp = 'wartungsvertrag_verlaengerung' and v_assignment.vorgaenger_zuordnung_id is not null) then
      return new;
    end if;
    raise exception 'Vorgangsart und Wartungsvertragszuordnung passen nicht zusammen.'
      using errcode = '23514';
  end if;

  if new.dokumenttyp = 'wartungsvertrag' then
    if new.vorgangstyp <> 'vertrag_signatur'
       or new.wartungsvertrag_id is null
       or new.parzelle_id is not null then
      raise exception 'Ein vorbereiteter Wartungsvertrag benötigt eine Vertragsdefinition.'
        using errcode = '23514';
    end if;
    select * into v_change
    from public.wartungsvertrag_grundlegende_aenderung
    where wartungsvertrag_id = new.wartungsvertrag_id
      and (kommunikationsvorgang_id = new.id or kommunikationsvorgang_id is null);
    if not found then
      raise exception 'Ein Wartungsvertrag ohne Zuordnung benötigt eine ausdrückliche grundlegende Änderung.'
        using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_wartungsvertrag_kommunikationsvorgang_link
  on public.kommunikationsvorgang;
create trigger trg_validate_wartungsvertrag_kommunikationsvorgang_link
  before insert or update of wartungsvertrag_zuordnung_id, wartungsvertrag_id,
    vorgangstyp, dokumenttyp, mitglied_id, parzelle_id
  on public.kommunikationsvorgang
  for each row execute function public.validate_wartungsvertrag_kommunikationsvorgang_link();

create or replace function public.ensure_wartungsvertrag_prepared_contract(p_zuordnung_id bigint)
returns public.kommunikationsvorgang
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_assignment public.wartungsvertrag_zuordnungen%rowtype;
  v_workflow public.wartungsvertrag_dokument_workflow%rowtype;
  v_contract public.kommunikationsvorgang%rowtype;
begin
  if not public.is_admin_or_vorstand() or auth.uid() is null then
    raise exception 'Nur administrative Vertragsbearbeitung darf Wartungsverträge vorbereiten.'
      using errcode = '42501';
  end if;

  select * into v_assignment
  from public.wartungsvertrag_zuordnungen
  where id = p_zuordnung_id;
  if not found then
    raise exception 'Die Wartungsvertragszuordnung wurde nicht gefunden.' using errcode = 'P0002';
  end if;

  perform public.ensure_wartungsvertrag_dokument_workflow(p_zuordnung_id);
  select * into v_workflow
  from public.wartungsvertrag_dokument_workflow
  where wartungsvertrag_zuordnung_id = p_zuordnung_id
  for update;

  if v_workflow.kommunikationsvorgang_id is not null then
    select * into v_contract
    from public.kommunikationsvorgang
    where id = v_workflow.kommunikationsvorgang_id;
    if not found then
      raise exception 'Der verknüpfte Wartungsvertragsvorgang fehlt.' using errcode = '23503';
    end if;
    return v_contract;
  end if;

  insert into public.kommunikationsvorgang(
    vorgangstyp, dokumenttyp, status, mitglied_id, parzelle_id,
    wartungsvertrag_zuordnung_id, wartungsvertrag_id, entwurf_daten,
    revision, zugewiesen_an
  )
  values (
    'vertrag_signatur', 'wartungsvertrag', 'vorbereitet',
    v_assignment.vertragspartei_mitglied_id, null, v_assignment.id, v_assignment.wartungsvertrag_id,
    jsonb_build_object(
      'schema_version', 'kgv-prepared-contract/v1',
      'document_type', 'wartungsvertrag',
      'memberId', v_assignment.vertragspartei_mitglied_id,
      'wartungsvertrag_zuordnung_id', v_assignment.id,
      'wartungsvertrag_id', v_assignment.wartungsvertrag_id,
      'gueltig_ab', v_assignment.gueltig_ab::text,
      'gueltig_bis', v_assignment.gueltig_bis::text,
      'wartungsvertrag_titel', (select titel from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id),
      'wartungsvertrag_beschreibung', (select beschreibung from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id),
      'wartungsvertrag_bereich', (select bereich from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id),
      'befreit_von_pflichtstunden', (select befreit_von_pflichtstunden from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id),
      'arbeitsstunden_gutschrift', (select arbeitsstunden_gutschrift from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id),
      'bemerkung', coalesce(v_assignment.bemerkung, (select bemerkung from public.wartungsvertraege where id = v_assignment.wartungsvertrag_id))
    ),
    1, auth.uid()
  )
  returning * into v_contract;

  update public.wartungsvertrag_dokument_workflow
  set kommunikationsvorgang_id = v_contract.id,
      status = 'dokument_ausstehend',
      fehlermeldung = null
  where id = v_workflow.id;
  return v_contract;
end;
$$;

create or replace function public.start_wartungsvertrag_grundlegende_aenderung(
  p_vorgaenger_zuordnung_id bigint,
  p_titel text,
  p_beschreibung text,
  p_bereich text,
  p_max_aktive_zuordnungen integer,
  p_befreit_von_pflichtstunden boolean,
  p_arbeitsstunden_gutschrift numeric,
  p_gueltig_ab date,
  p_bemerkung text default null
)
returns table (kommunikationsvorgang_id bigint, wartungsvertrag_id bigint, status text)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_old public.wartungsvertrag_zuordnungen%rowtype;
  v_old_contract public.wartungsvertraege%rowtype;
  v_change public.wartungsvertrag_grundlegende_aenderung%rowtype;
  v_new_contract public.wartungsvertraege%rowtype;
  v_communication public.kommunikationsvorgang%rowtype;
begin
  if auth.uid() is null or not public.is_admin_or_vorstand() then
    raise exception 'Nur Admin oder Vorstand darf eine grundlegende Wartungsvertragsänderung starten.'
      using errcode = '42501';
  end if;

  select * into v_old
  from public.wartungsvertrag_zuordnungen
  where id = p_vorgaenger_zuordnung_id
  for update;
  if not found or (v_old.gueltig_bis is not null and v_old.gueltig_bis < current_date) then
    raise exception 'Die Ausgangszuordnung ist nicht mehr aktuell.' using errcode = '23514';
  end if;
  if v_old.vertragspartei_mitglied_id is null then
    raise exception 'Die tatsächliche Vertragspartei des Altvertrags ist ungeklärt; es wird nicht geraten.'
      using errcode = '23514';
  end if;
  if exists (
    select 1
    from public.wartungsvertrag_zuordnungen successor
    where successor.vorgaenger_zuordnung_id = v_old.id
  ) then
    raise exception 'Für die Ausgangszuordnung besteht bereits eine Folgezuordnung.'
      using errcode = '23514';
  end if;

  select * into v_change
  from public.wartungsvertrag_grundlegende_aenderung
  where vorgaenger_zuordnung_id = v_old.id
  for update;
  if found then
    select * into v_communication
    from public.kommunikationsvorgang
    where id = v_change.kommunikationsvorgang_id;
    if not found then
      raise exception 'Der vorgemerkte Signaturvorgang fehlt.' using errcode = '23503';
    end if;
    return query select v_communication.id, v_change.wartungsvertrag_id, v_communication.status;
    return;
  end if;

  if nullif(btrim(p_titel), '') is null
     or p_max_aktive_zuordnungen < 1
     or p_arbeitsstunden_gutschrift < 0
     or (p_befreit_von_pflichtstunden and p_arbeitsstunden_gutschrift > 0)
     or p_gueltig_ab is null
     or p_gueltig_ab < current_date
     or p_gueltig_ab <= v_old.gueltig_ab then
    raise exception 'Die Vertragsdaten oder der neue Gültigkeitsbeginn sind ungültig.'
      using errcode = '22023';
  end if;

  select * into v_old_contract
  from public.wartungsvertraege
  where id = v_old.wartungsvertrag_id
  for key share;
  if not found then
    raise exception 'Die Vertragsdefinition des Altvertrags fehlt.' using errcode = '23503';
  end if;

  insert into public.wartungsvertraege(
    titel, beschreibung, bereich, max_aktive_zuordnungen,
    befreit_von_pflichtstunden, arbeitsstunden_gutschrift, aktiv,
    bemerkung, is_demo
  )
  values (
    btrim(p_titel), nullif(btrim(p_beschreibung), ''), nullif(btrim(p_bereich), ''),
    p_max_aktive_zuordnungen, p_befreit_von_pflichtstunden,
    p_arbeitsstunden_gutschrift, false, nullif(btrim(p_bemerkung), ''),
    v_old_contract.is_demo
  )
  returning * into v_new_contract;

  insert into public.wartungsvertrag_grundlegende_aenderung(
    vorgaenger_zuordnung_id, wartungsvertrag_id
  )
  values (v_old.id, v_new_contract.id)
  returning * into v_change;

  insert into public.kommunikationsvorgang(
    vorgangstyp, dokumenttyp, status, mitglied_id, parzelle_id,
    wartungsvertrag_id, entwurf_daten, revision, zugewiesen_an
  )
  values (
    'vertrag_signatur', 'wartungsvertrag', 'vorbereitet',
    v_old.vertragspartei_mitglied_id, null, v_new_contract.id,
    jsonb_build_object(
      'schema_version', 'kgv-prepared-contract/v1',
      'document_type', 'wartungsvertrag',
      'memberId', v_old.vertragspartei_mitglied_id,
      'wartungsvertrag_id', v_new_contract.id,
      'wartungsvertrag_zuordnung_id', null,
      'vorgaenger_zuordnung_id', v_old.id,
      'gueltig_ab', p_gueltig_ab::text,
      'gueltig_bis', null,
      'wartungsvertrag_titel', v_new_contract.titel,
      'wartungsvertrag_beschreibung', v_new_contract.beschreibung,
      'wartungsvertrag_bereich', v_new_contract.bereich,
      'befreit_von_pflichtstunden', v_new_contract.befreit_von_pflichtstunden,
      'arbeitsstunden_gutschrift', v_new_contract.arbeitsstunden_gutschrift,
      'bemerkung', v_new_contract.bemerkung
    ),
    1, auth.uid()
  )
  returning * into v_communication;

  update public.wartungsvertrag_grundlegende_aenderung
  set kommunikationsvorgang_id = v_communication.id
  where id = v_change.id;

  return query select v_communication.id, v_new_contract.id, v_communication.status;
end;
$$;

create or replace function public.complete_prepared_wartungsvertrag(
  p_kommunikationsvorgang_id bigint,
  p_dokument_id bigint
)
returns table (wartungsvertrag_zuordnung_id bigint, bereits_abgeschlossen boolean)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_communication public.kommunikationsvorgang%rowtype;
  v_document public.dokument%rowtype;
  v_assignment public.wartungsvertrag_zuordnungen%rowtype;
  v_old public.wartungsvertrag_zuordnungen%rowtype;
  v_change public.wartungsvertrag_grundlegende_aenderung%rowtype;
  v_draft jsonb;
  v_member_id bigint;
  v_start date;
begin
  select * into v_communication
  from public.kommunikationsvorgang
  where id = p_kommunikationsvorgang_id
  for update;
  if not found
     or v_communication.vorgangstyp <> 'vertrag_signatur'
     or v_communication.dokumenttyp <> 'wartungsvertrag'
     or v_communication.signatur_revision is null then
    raise exception 'Der Wartungsvertrags-Signaturvorgang ist ungültig.' using errcode = '23514';
  end if;

  select * into v_document
  from public.dokument
  where id = p_dokument_id
    and source_kommunikationsvorgang_id = v_communication.id
    and source_revision = v_communication.signatur_revision
    and archiviert_at is null
  for key share;
  if not found or v_document.mitglied_id is distinct from v_communication.mitglied_id then
    raise exception 'Das finale Wartungsvertragsdokument passt nicht zum Signaturvorgang.'
      using errcode = '23514';
  end if;

  if v_communication.status = 'erledigt' then
    if v_communication.final_dokument_id is distinct from p_dokument_id
       or v_communication.wartungsvertrag_zuordnung_id is null then
      raise exception 'Der abgeschlossene Wartungsvertrag verweist auf ein anderes Dokument.'
        using errcode = '23514';
    end if;
    return query select v_communication.wartungsvertrag_zuordnung_id, true;
    return;
  end if;
  if v_communication.status not in ('zur_signatur', 'letzte_pruefung')
     or v_communication.wartungsvertrag_id is null then
    raise exception 'Der Wartungsvertrag ist nicht vollständig signaturbereit.'
      using errcode = '23514';
  end if;
  if public.prepared_contract_signaturen_vollstaendig(
    v_communication.id,
    v_communication.signatur_revision
  ) is distinct from true then
    raise exception 'Alle erforderlichen Wartungsvertragsunterschriften müssen vor dem Abschluss vorliegen.'
      using errcode = '23514';
  end if;

  select * into v_assignment
  from public.wartungsvertrag_zuordnungen
  where id = v_communication.wartungsvertrag_zuordnung_id
  for update;

  if v_assignment.id is null then
    select * into v_change
    from public.wartungsvertrag_grundlegende_aenderung
    where kommunikationsvorgang_id = v_communication.id
    for update;
    if not found or v_change.wartungsvertrag_id is distinct from v_communication.wartungsvertrag_id then
      raise exception 'Der neue Wartungsvertrag wurde nicht ausdrücklich aus einer grundlegenden Änderung vorbereitet.'
        using errcode = '23514';
    end if;

    select * into v_old
    from public.wartungsvertrag_zuordnungen
    where id = v_change.vorgaenger_zuordnung_id
    for update;
    if not found or v_old.vertragspartei_mitglied_id is distinct from v_communication.mitglied_id then
      raise exception 'Der Vorgänger passt nicht zum neuen Wartungsvertrag.'
        using errcode = '23514';
    end if;

    v_draft := v_communication.entwurf_daten;
    v_start := (v_draft ->> 'gueltig_ab')::date;
    v_member_id := v_old.vertragspartei_mitglied_id;
    if v_start is null or v_start <= v_old.gueltig_ab then
      raise exception 'Der neue Vertragsbeginn ist ungültig.' using errcode = '23514';
    end if;

    insert into public.wartungsvertrag_zuordnungen(
      wartungsvertrag_id, hauptmitglied_id, vertragspartei_mitglied_id,
      gueltig_ab, gueltig_bis, bemerkung
    )
    values (
      v_communication.wartungsvertrag_id, v_old.hauptmitglied_id,
      v_member_id, v_start, null,
      (select nullif(btrim(w.bemerkung), '')
       from public.wartungsvertraege w
       where w.id = v_communication.wartungsvertrag_id)
    )
    returning * into v_assignment;

    if v_old.gueltig_bis is null or v_old.gueltig_bis >= v_start then
      update public.wartungsvertrag_zuordnungen
      set gueltig_bis = v_start - 1
      where id = v_old.id;
    end if;

    update public.wartungsvertraege
    set aktiv = true
    where id = v_communication.wartungsvertrag_id;

    update public.kommunikationsvorgang
    set wartungsvertrag_zuordnung_id = v_assignment.id
    where id = v_communication.id;

    update public.dokument
    set source_wartungsvertrag_zuordnung_id = v_assignment.id
    where id = v_document.id;

    update public.wartungsvertrag_dokument_workflow
    set kommunikationsvorgang_id = v_communication.id,
        status = 'signatur_vorgang',
        fehlermeldung = null
    where wartungsvertrag_zuordnung_id = v_assignment.id;

    update public.wartungsvertrag_grundlegende_aenderung
    set neue_zuordnung_id = v_assignment.id,
        status = 'erledigt',
        erledigt_am = now()
    where id = v_change.id;
  else
    if v_assignment.wartungsvertrag_id is distinct from v_communication.wartungsvertrag_id
       or v_assignment.vertragspartei_mitglied_id is distinct from v_communication.mitglied_id
       or v_document.source_wartungsvertrag_zuordnung_id is distinct from v_assignment.id then
      raise exception 'Das finale Wartungsvertragsdokument passt nicht zur Vertragszuordnung.'
        using errcode = '23514';
    end if;
  end if;

  if v_communication.status = 'zur_signatur' then
    update public.kommunikationsvorgang
    set final_dokument_id = p_dokument_id,
        status = 'letzte_pruefung'
    where id = v_communication.id;
  elsif v_communication.final_dokument_id is distinct from p_dokument_id then
    raise exception 'Der Wartungsvertragsvorgang verweist auf ein anderes finales Dokument.'
      using errcode = '23514';
  end if;

  update public.kommunikationsvorgang
  set status = 'erledigt'
  where id = v_communication.id
    and status = 'letzte_pruefung';

  return query select v_assignment.id, false;
end;
$$;

create or replace function public.validate_wartungsvertrag_dokument_workflow()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_assignment public.wartungsvertrag_zuordnungen%rowtype;
  v_communication public.kommunikationsvorgang%rowtype;
  v_document public.dokument%rowtype;
begin
  select * into v_assignment
  from public.wartungsvertrag_zuordnungen
  where id = new.wartungsvertrag_zuordnung_id;
  if not found then
    raise exception 'Die Wartungsvertragszuordnung für den Dokumentvorgang wurde nicht gefunden.'
      using errcode = '23503';
  end if;

  if new.workflow_art = 'erstvertrag' and new.folgeentscheidung_id is not null then
    raise exception 'Ein Erstvertragsworkflow darf keine Folgeentscheidung referenzieren.'
      using errcode = '23514';
  end if;
  if new.workflow_art = 'verlaengerungsmitteilung' and v_assignment.vorgaenger_zuordnung_id is null then
    raise exception 'Eine Verlängerungsmitteilung benötigt eine Folgezuordnung.'
      using errcode = '23514';
  end if;
  if new.workflow_art = 'verlaengerungsmitteilung'
     and new.kommunikationsvorgang_id is not null
     and new.folgeentscheidung_id is null then
    raise exception 'Eine vorbereitete Verlängerungsmitteilung benötigt eine Folgeentscheidung.'
      using errcode = '23514';
  end if;

  if new.kommunikationsvorgang_id is not null then
    select * into v_communication
    from public.kommunikationsvorgang
    where id = new.kommunikationsvorgang_id;
    if not found
       or v_communication.wartungsvertrag_zuordnung_id is distinct from new.wartungsvertrag_zuordnung_id
       or v_communication.mitglied_id is distinct from v_assignment.vertragspartei_mitglied_id
       or (new.workflow_art = 'erstvertrag' and (v_communication.vorgangstyp <> 'vertrag_signatur' or v_communication.dokumenttyp <> 'wartungsvertrag'))
       or (new.workflow_art = 'verlaengerungsmitteilung' and (v_communication.vorgangstyp <> 'dokument_erzeugung' or v_communication.dokumenttyp <> 'wartungsvertrag_verlaengerung')) then
      raise exception 'Der Signaturvorgang passt nicht zur Wartungsvertragszuordnung und ihrer Vertragspartei.'
        using errcode = '23514';
    end if;
  end if;

  if new.dokument_id is not null then
    select * into v_document
    from public.dokument
    where id = new.dokument_id;
    if not found
       or v_document.mitglied_id is distinct from v_assignment.vertragspartei_mitglied_id
       or (new.workflow_art = 'erstvertrag' and v_document.source_wartungsvertrag_zuordnung_id is distinct from new.wartungsvertrag_zuordnung_id) then
      raise exception 'Das Wartungsvertragsdokument passt nicht zur Zuordnung und ihrer Vertragspartei.'
        using errcode = '23514';
    end if;
  end if;

  new.bearbeitet_am := now();
  return new;
end;
$$;

