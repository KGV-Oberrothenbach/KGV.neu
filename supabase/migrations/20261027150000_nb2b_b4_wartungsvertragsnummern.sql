  check (quelle_art in ('kommunikationsvorgang', 'historisches_dokument', 'wartungsvertrag'));

-- Preserve the earliest existing reservation for each maintenance contract.
-- Other historical communication reservations are retained for auditability.
do $$
declare
  v_reservation record;
begin
  for v_reservation in
    select distinct on (wz.wartungsvertrag_id, fr.is_demo)
      wz.wartungsvertrag_id,
      fr.is_demo,
      fr.quelle_art,
      fr.quelle_id
    from public.kommunikationsvorgang kv
    join public.wartungsvertrag_zuordnungen wz
      on wz.id = kv.wartungsvertrag_zuordnung_id
    join public.fachnummer_reservierung fr
      on fr.quelle_art = 'kommunikationsvorgang'
     and fr.quelle_id = kv.id
     and fr.art = 'wartungsvertrag'
     and fr.is_demo = coalesce((select w.is_demo from public.wartungsvertraege w where w.id = wz.wartungsvertrag_id), false)
    where not exists (
      select 1
      from public.fachnummer_reservierung canonical
      where canonical.quelle_art = 'wartungsvertrag'
        and canonical.quelle_id = wz.wartungsvertrag_id
        and canonical.is_demo = fr.is_demo
    )
    order by wz.wartungsvertrag_id, fr.is_demo, fr.reserviert_am, fr.nummer
  loop
    update public.fachnummer_reservierung
    set quelle_art = 'wartungsvertrag',
        quelle_id = v_reservation.wartungsvertrag_id
    where quelle_art = v_reservation.quelle_art
      and quelle_id = v_reservation.quelle_id
      and is_demo = v_reservation.is_demo;
  end loop;
end;
$$;

create or replace function public.validate_wartungsvertrag_document_source()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_assignment public.wartungsvertrag_zuordnungen%rowtype;
  v_communication public.kommunikationsvorgang%rowtype;
begin
  if new.source_wartungsvertrag_zuordnung_id is null then
    return new;
  end if;

  select * into v_assignment
  from public.wartungsvertrag_zuordnungen
  where id = new.source_wartungsvertrag_zuordnung_id;
  if not found then
    raise exception 'Die Wartungsvertragszuordnung des Dokuments wurde nicht gefunden.'
      using errcode = '23503';
  end if;

  select * into v_communication
  from public.kommunikationsvorgang
  where id = new.source_kommunikationsvorgang_id;
  if not found
     or v_communication.vorgangstyp <> 'vertrag_signatur'
     or v_communication.dokumenttyp <> 'wartungsvertrag'
     or v_communication.wartungsvertrag_zuordnung_id is distinct from new.source_wartungsvertrag_zuordnung_id
     or new.mitglied_id is distinct from v_assignment.vertragspartei_mitglied_id then
    raise exception 'Das finale Wartungsvertragsdokument passt nicht zum Signaturvorgang und zur Vertragspartei.'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

