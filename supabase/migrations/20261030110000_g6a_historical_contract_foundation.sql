-- Register a historical MA+PV initial contract or PV follow-up atomically.
-- p_vorherige_enddaten maps a pachtverhaeltnis id to an explicitly selected
-- predecessor end date. Omitting a key uses the day before this contract begins.
create or replace function public.register_historischen_pachtvertrag(
  p_dokument_id bigint,
  p_dokumenttyp_code text,
  p_vertragsdatum date,
  p_unterzeichnet boolean,
  p_pachtverhaeltnis_ids bigint[],
  p_vorherige_enddaten jsonb default '{}'::jsonb,
  p_mitglied_seit_korrektur_mitglied_id bigint default null,
  p_mitglied_seit_korrektur_datum date default null
)
returns table (
  dokument_id bigint,
  dokumenttyp_id bigint,
  pachtverhaeltnis_id bigint,
  pachtvertragsfassung_id bigint,
  historische_vertragsnummer integer
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_dokument public.dokument%rowtype;
  v_dokumenttyp_id bigint;
  v_hat_ma_nachweis boolean;
  v_hat_pv_nachweis boolean;
  v_relation_id bigint;
  v_fassung_id bigint;
  v_vorgaenger_id bigint;
  v_nachfolger_id bigint;
  v_vorgaenger_ende date;
  v_nachfolger_beginn date;
  v_nummer integer;
  v_is_demo boolean;
  v_old_mitglied_seit date;
begin
  if not public.can_register_historical_contracts() then
    raise exception 'Für die Nacherfassung historischer Verträge fehlt die Berechtigung.' using errcode = '42501';
  end if;
  if p_vertragsdatum is null or p_unterzeichnet is null then
    raise exception 'Vertragsdatum und Signaturstatus sind erforderlich.' using errcode = '22023';
  end if;
  if coalesce(array_length(p_pachtverhaeltnis_ids, 1), 0) = 0
     or exists (select 1 from unnest(p_pachtverhaeltnis_ids) id group by id having count(*) > 1) then
    raise exception 'Mindestens eine eindeutige Pachtbeziehung ist erforderlich.' using errcode = '22023';
  end if;

  select * into v_dokument from public.dokument where id = p_dokument_id for update;
  if not found or v_dokument.archiviert_at is not null then
    raise exception 'Das Dokument existiert nicht oder ist bereits archiviert.' using errcode = 'P0002';
  end if;
  if v_dokument.source_kommunikationsvorgang_id is not null or v_dokument.source_wartungsvertrag_zuordnung_id is not null then
    raise exception 'Prepared-Dokumente dürfen nicht als historische Verträge registriert werden.' using errcode = '23514';
  end if;
  if v_dokument.mitglied_id is null then
    raise exception 'Ein historischer Vertrag benötigt ein zugeordnetes bestehendes Mitglied.' using errcode = '22023';
  end if;

  select dt.id,
      exists(select 1 from public.dokumenttyp_wirkung w where w.dokumenttyp_id = dt.id and w.wirkung = 'mitgliedsantrag_nachweis'),
      exists(select 1 from public.dokumenttyp_wirkung w where w.dokumenttyp_id = dt.id and w.wirkung = 'pachtvertrag_nachweis')
  into v_dokumenttyp_id, v_hat_ma_nachweis, v_hat_pv_nachweis
  from public.dokumenttyp dt where dt.code = p_dokumenttyp_code and dt.aktiv;
  if not found or p_dokumenttyp_code not in ('historischer_ma_pv_erstvertrag', 'historischer_pv_folgevertrag')
     or not v_hat_pv_nachweis then
    raise exception 'Der Dokumenttyp ist kein zulässiger historischer Pachtvertrag.' using errcode = '22023';
  end if;

  if v_dokument.dokumenttyp_id is not null
     and (v_dokument.dokumenttyp_id is distinct from v_dokumenttyp_id
       or v_dokument.dokumentdatum is distinct from p_vertragsdatum
       or v_dokument.unterzeichnet is distinct from p_unterzeichnet) then
    raise exception 'Das Dokument ist bereits abweichend klassifiziert.' using errcode = '23514';
  end if;

  foreach v_relation_id in array p_pachtverhaeltnis_ids loop
    if not exists (select 1 from public.pachtverhaeltnis where id = v_relation_id) then
      raise exception 'Unbekanntes Pachtverhältnis: %', v_relation_id using errcode = 'P0002';
    end if;
    if not exists (
      select 1 from public.pachtverhaeltnis_beteiligung b
      where b.pachtverhaeltnis_id = v_relation_id and b.mitglied_id = v_dokument.mitglied_id
        and b.gueltig_ab <= p_vertragsdatum and (b.gueltig_bis is null or b.gueltig_bis >= p_vertragsdatum)
    ) then
      raise exception 'Das Dokumentmitglied war am Vertragsdatum nicht an Pachtverhältnis % beteiligt.', v_relation_id using errcode = '23514';
    end if;
  end loop;

  update public.dokument set dokumenttyp_id = v_dokumenttyp_id, dokumentdatum = p_vertragsdatum,
    unterzeichnet = p_unterzeichnet, updated_at = now() where id = p_dokument_id;

  foreach v_relation_id in array p_pachtverhaeltnis_ids loop
    select id, gueltig_bis into v_fassung_id from public.pachtvertragsfassung
      where dokument_id = p_dokument_id and pachtverhaeltnis_id = v_relation_id for update;

    if found then
      if not exists (select 1 from public.pachtvertragsfassung f where f.id = v_fassung_id and f.fassungstyp = 'import' and f.wirksam_ab = p_vertragsdatum) then
        raise exception 'Das Dokument ist für Pachtverhältnis % bereits abweichend registriert.', v_relation_id using errcode = '23514';
      end if;
    else
      select id into v_vorgaenger_id from public.pachtvertragsfassung
        where pachtverhaeltnis_id = v_relation_id and wirksam_ab < p_vertragsdatum
        order by wirksam_ab desc, id desc limit 1 for update;
      select id, wirksam_ab into v_nachfolger_id, v_nachfolger_beginn from public.pachtvertragsfassung
        where pachtverhaeltnis_id = v_relation_id and wirksam_ab > p_vertragsdatum
        order by wirksam_ab, id limit 1 for update;

      insert into public.pachtvertragsfassung(pachtverhaeltnis_id, dokument_id, fassungstyp, vertragsdatum, wirksam_ab, gueltig_bis, vorgaenger_fassung_id)
      values (v_relation_id, p_dokument_id, 'import', p_vertragsdatum, p_vertragsdatum,
        case when v_nachfolger_beginn is null then null else v_nachfolger_beginn - 1 end, v_vorgaenger_id)
      returning id into v_fassung_id;

      if v_vorgaenger_id is not null then
        v_vorgaenger_ende := coalesce(nullif(p_vorherige_enddaten ->> v_relation_id::text, '')::date, p_vertragsdatum - 1);
        update public.pachtvertragsfassung set gueltig_bis = v_vorgaenger_ende where id = v_vorgaenger_id;
      end if;
      if v_nachfolger_id is not null then
        update public.pachtvertragsfassung set vorgaenger_fassung_id = v_fassung_id where id = v_nachfolger_id;
      end if;
    end if;

  end loop;

  -- Uses the established 80xxx reservation source and only broadens its permission gate.
  select coalesce(is_demo, false) into v_is_demo from public.mitglied where id = v_dokument.mitglied_id;
  v_nummer := public.reserve_fachnummer('historischer_kombivertrag', 'historisches_dokument', p_dokument_id, v_is_demo);
  update public.dokument set historische_vertragsnummer = v_nummer,
    titel = regexp_replace(coalesce(nullif(btrim(titel), ''), 'Historischer Vertrag'), '\s*·\s*Vertrags-Nr\.\s*\d{5}\s*$', '', 'i') || ' · Vertrags-Nr. ' || v_nummer,
    updated_at = now() where id = p_dokument_id;

  if p_mitglied_seit_korrektur_mitglied_id is not null or p_mitglied_seit_korrektur_datum is not null then
    if not v_hat_ma_nachweis or p_mitglied_seit_korrektur_mitglied_id is null or p_mitglied_seit_korrektur_datum is null then
      raise exception 'Mitglied-seit-Korrekturen sind nur bewusst beim MA+PV-Erstvertrag zulässig.' using errcode = '22023';
    end if;
    select mitglied_seit into v_old_mitglied_seit from public.mitglied where id = p_mitglied_seit_korrektur_mitglied_id for update;
    if not found then raise exception 'Mitglied für die Korrektur nicht gefunden.' using errcode = 'P0002'; end if;
    update public.mitglied set mitglied_seit = p_mitglied_seit_korrektur_datum where id = p_mitglied_seit_korrektur_mitglied_id;
    insert into public.mitglied_historische_korrektur(mitglied_id, dokument_id, feld, bisheriger_wert, korrigierter_wert, korrigiert_von)
    values (p_mitglied_seit_korrektur_mitglied_id, p_dokument_id, 'mitglied_seit', v_old_mitglied_seit, p_mitglied_seit_korrektur_datum, auth.uid())
    on conflict (mitglied_id, dokument_id, feld) do nothing;
  end if;

  return query select p_dokument_id, v_dokumenttyp_id, f.pachtverhaeltnis_id, f.id, v_nummer
    from public.pachtvertragsfassung f where f.dokument_id = p_dokument_id order by f.pachtverhaeltnis_id;
end;
$$;
revoke all on function public.register_historischen_pachtvertrag(bigint, text, date, boolean, bigint[], jsonb, bigint, date) from public, anon;
grant execute on function public.register_historischen_pachtvertrag(bigint, text, date, boolean, bigint[], jsonb, bigint, date) to authenticated, service_role;
-- Historical numbers must remain in the existing 80xxx circle, but the dedicated
-- capability may invoke that circle for an historical document.
create or replace function public.reserve_fachnummer(p_art text, p_quelle_art text, p_quelle_id bigint, p_is_demo boolean)
returns integer language plpgsql security definer set search_path = public, pg_temp as $$
declare v_nummer integer; v_bestehende_art text; v_sequenz regclass;
begin
  if not public.is_admin_or_vorstand() and auth.role() <> 'service_role'
     and not (p_art = 'historischer_kombivertrag' and public.can_register_historical_contracts()) then
    raise exception 'Keine Berechtigung für Nummernvergabe' using errcode = '42501';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(concat_ws(':', p_is_demo::text, p_quelle_art, p_quelle_id::text), 0));
  select nummer, art into v_nummer, v_bestehende_art from public.fachnummer_reservierung where is_demo = p_is_demo and quelle_art = p_quelle_art and quelle_id = p_quelle_id;
  if found then
    if v_bestehende_art <> p_art then raise exception 'Die Quelle besitzt bereits eine Reservierung der Art % und kann nicht als % verwendet werden.', v_bestehende_art, p_art using errcode = '22023'; end if;
    return v_nummer;
  end if;
  v_sequenz := case when p_is_demo then case p_art when 'mitgliedsantrag' then 'public.fachnummer_mitgliedsantrag_demo_seq'::regclass when 'pachtvertrag' then 'public.fachnummer_pachtvertrag_demo_seq'::regclass when 'historischer_kombivertrag' then 'public.fachnummer_historisch_demo_seq'::regclass when 'wartungsvertrag' then 'public.fachnummer_wartungsvertrag_demo_seq'::regclass end else case p_art when 'mitgliedsantrag' then 'public.fachnummer_mitgliedsantrag_seq'::regclass when 'pachtvertrag' then 'public.fachnummer_pachtvertrag_seq'::regclass when 'historischer_kombivertrag' then 'public.fachnummer_historisch_seq'::regclass when 'wartungsvertrag' then 'public.fachnummer_wartungsvertrag_seq'::regclass end end;
  if v_sequenz is null then raise exception 'Unbekannte Nummernart' using errcode = '22023'; end if;
  v_nummer := nextval(v_sequenz);
  insert into public.fachnummer_reservierung(is_demo, nummer, art, quelle_art, quelle_id) values (p_is_demo, v_nummer, p_art, p_quelle_art, p_quelle_id);
  return v_nummer;
end;
$$;
create or replace function public.reserve_historische_vertragsnummer(p_dokument_id bigint)
returns table (nummer integer, titel text, mime_type text, pdf_bereits_gestempelt boolean)
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_dokument public.dokument%rowtype; v_is_demo boolean; v_nummer integer; v_titel text;
begin
  if not public.can_register_historical_contracts() then
    raise exception 'Für die Nacherfassung historischer Verträge fehlt die Berechtigung.' using errcode = '42501';
  end if;
  select * into v_dokument from public.dokument where id = p_dokument_id for update;
  if not found or v_dokument.archiviert_at is not null then raise exception 'Das historische Dokument existiert nicht oder ist archiviert.' using errcode = 'P0002'; end if;
  if v_dokument.mitglied_id is null then raise exception 'Ohne ausgewähltes Mitglied darf keine historische Vertragsnummer reserviert werden.' using errcode = '22023'; end if;
  select coalesce(is_demo, false) into v_is_demo from public.mitglied where id = v_dokument.mitglied_id;
  if not found then raise exception 'Das ausgewählte Mitglied existiert nicht.' using errcode = 'P0002'; end if;
  v_nummer := public.reserve_fachnummer('historischer_kombivertrag', 'historisches_dokument', p_dokument_id, v_is_demo);
  v_titel := regexp_replace(coalesce(nullif(btrim(v_dokument.titel), ''), 'Historischer Vertrag'), '\s*·\s*Vertrags-Nr\.\s*\d{5}\s*$', '', 'i') || ' · Vertrags-Nr. ' || v_nummer;
  update public.dokument set historische_vertragsnummer = v_nummer, titel = v_titel, updated_at = now() where id = p_dokument_id;
  return query select v_nummer, v_titel, v_dokument.mime_type, v_dokument.historische_vertragsnummer_pdf_gestempelt_am is not null;
end;
$$;
create or replace function public.mark_historische_vertragsnummer_pdf_gestempelt(p_dokument_id bigint, p_nummer integer)
returns void
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if not public.can_register_historical_contracts() then
    raise exception 'Für die Nacherfassung historischer Verträge fehlt die Berechtigung.' using errcode = '42501';
  end if;
  update public.dokument set historische_vertragsnummer_pdf_gestempelt_am = coalesce(historische_vertragsnummer_pdf_gestempelt_am, now()), updated_at = now()
  where id = p_dokument_id and historische_vertragsnummer = p_nummer;
  if not found then raise exception 'Die historische Vertragsnummer passt nicht zum Dokument.' using errcode = '22023'; end if;
end;
$$;
