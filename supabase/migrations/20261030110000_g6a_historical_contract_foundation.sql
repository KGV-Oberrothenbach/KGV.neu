create or replace function public.can_register_historical_contracts()
returns boolean
language sql
stable
security definer
set search_path to 'public', 'pg_temp'
as $$
  select auth.role() = 'service_role'
      or (auth.uid() is not null and public.has_effective_permission(16777216));
$$;
revoke all on function public.can_register_historical_contracts() from public, anon;
grant execute on function public.can_register_historical_contracts() to authenticated, service_role;
